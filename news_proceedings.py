"""Процессуальные решения в отношении действующего регионального руководства.

Это эвристический отбор публикаций, не юридическая проверка обвинений.
Для включения нужны: (1) действующая должность высшего уровня,
(2) процессуальное действие, (3) явно названный официальный источник в
заголовке или первом абзаце, (4) региональная привязка (проверяется выше).
"""
import re

# Отмечаем лишь региональных руководителей, не федеральных чиновников и
# не руководителей муниципального или ведомственного среднего звена.
ROLE = re.compile(
    r"\b(?:врио\s+)?(?:губернатор\w*|вице[\-\s]?губернатор\w*|"
    r"(?:перв\w+\s+)?зам(?:естител\w*|губернатор\w*)\s+губернатор\w*|"
    r"глав[аыеу]\s+(?:республик\w*|регион\w*)|"
    r"председател\w*\s+правительств\w*|"
    r"(?:перв\w+\s+)?заместител\w*\s+председател\w*\s+правительств\w*|"
    r"вице[\-\s]?премьер\w*|"
    r"(?:перв\w+\s+)?зам(?:естител\w*)?\s+министр\w*|"
    r"министр\w*)(?![а-яё])",
    re.I,
)
# Не допускаем ни бывших руководителей, ни экс-заместителей.
FORMER = re.compile(r"\b(?:экс[\-\s]?|бывш\w*|прежн\w*|ранее\s+(?:занимавш\w*|возглавлявш\w*))\s*$", re.I)
REGION_CUE = re.compile(
    r"\b(?:Мурманск\w*|Архангельск\w*|Вологодск\w*|Ленинградск\w*|"
    r"Псковск\w*|Новгородск\w*|Калининградск\w*|Петербург\w*|"
    r"Санкт[\-\s]?Петербург\w*|Карели\w*|Коми\b|Ненецк\w*|"
    r"Ленобласт\w*|област\w*|республик\w*)\b", re.I
)
# Заголовок / первое предложение должны содержать конкретную стадию.
# Приоритет позволяет отличать арест от первоначального задержания.
STAGES = (
    ("arrest", re.compile(r"\b(?:арестовал\w*|арестован\w*|заключ[её]н\w*\s+под\s+стражу|"
                         r"взят\w*\s+под\s+стражу|арест\w*|отправлен\w*\s+в\s+СИЗО|"
                         r"избран\w*\s+мер\w*\s+пресечени\w*|домашн\w*\s+арест)\b", re.I)),
    ("charge", re.compile(r"\b(?:предъявлен\w*\s+обвинени\w*|обвинени\w*\s+предъявлен\w*|"
                         r"предъявил\w*\s+обвинени\w*|обвиняем\w*|привлеч[её]н\w*\s+в\s+качестве\s+обвиняем\w*)\b", re.I)),
    ("detention", re.compile(r"\b(?:задержан\w*|задержал\w*|задержали|задержани\w*)\b", re.I)),
    ("case", re.compile(r"\b(?:возбужден\w*\s+уголовн\w*\s+дел\w*|"
                       r"возбудил\w*\s+уголовн\w*\s+дел\w*|"
                       r"уголовн\w*\s+дел\w*\s+(?:возбужден\w*|возбудил\w*))\b", re.I)),
    ("verdict", re.compile(r"\b(?:приговор[её]н\w*|приговорил\w*|осужд[её]н\w*|вынес\w*\s+приговор)\b", re.I)),
    ("released", re.compile(r"\b(?:освобожд[её]н\w*\s+из[\-\s]под\s+стражи|"
                           r"отпущен\w*\s+из[\-\s]под\s+стражи|"
                           r"прекращен\w*\s+уголовн\w*\s+дел\w*|"
                           r"уголовн\w*\s+дел\w*\s+прекращен\w*)\b", re.I)),
)
# Источник подтверждения должен быть явно назван. «По словам источника»
# или «пишут СМИ» недостаточно. Извлечение текста из RSS ограничивает
# достоверность: сама публикация всё равно может оказаться ошибочной.
AUTHORITY = re.compile(
    r"\b(?:МВД(?:\s+России)?|Следственн\w*\s+комитет\w*|"
    r"(?:СУ\s+)?СКР?\b|прокуратур\w*|Генпрокуратур\w*|"
    r"ФСБ(?:\s+России)?|суд\w*|УМВД|ГУ\s*МВД|"
    r"официальн\w*\s+представител\w*\s+МВД|"
    r"пресс[\-\s]?служб\w*\s+(?:МВД|СК|ФСБ|суд\w*))\b", re.I
)
# Упоминания «МВД» в заметке недостаточно. Нужна положительная
# атрибуция события ведомству или суду («сообщили», «подтвердили»,
# «сотрудниками МВД задержан»). Это не заменяет проверку первоисточника.
OFFICIAL_REPORT = re.compile(
    r"(?:\b(?:МВД|Следственн\w*\s+комитет\w*|\bСКР?\b|прокуратур\w*|"
    r"ФСБ|Генпрокуратур\w*|суд\w*|УМВД|ГУ\s*МВД)\b(?:\s+[А-Яа-яЁё.]+){0,6}?\s+"
    r"(?:сообщил\w*|подтвердил\w*|задержал\w*|арестовал\w*|"
    r"возбудил\w*|предъявил\w*|приговорил\w*|постановил\w*)|"
    r"\bсотрудник\w*\s+(?:МВД|СК|ФСБ)(?:\s+России)?\s+"
    r"(?:задержан\w*|задержал\w*|арестовал\w*)|"
    r"\b(?:по\s+(?:сообщению|информации|заявлению)|сообщил\w*\s+в|"
    r"подтвердил\w*\s+в)\s+(?:МВД|СК|ФСБ|прокуратур\w*)|"
    r"\b(?:в\s+МВД|в\s+СК|в\s+прокуратур\w*)\s+(?:России\s+)?"
    r"(?:сообщил\w*|подтвердил\w*))", re.I
)

# Не публикуем явные опровержения, предположения, слухи и вопросительные
# заголовки как установленное процессуальное событие.
UNCONFIRMED = re.compile(
    r"\b(?:опроверг\w*|не\s+подтвердил\w*|не\s+комментиру\w*|не\s+располага\w*|"
    r"ложн\w*\s+сообщени\w*|фейк\w*|"
    r"по\s+данным\s+(?:анонимн\w*\s+)?источник\w*|"
    r"по\s+слухам|предполагаем\w*\s+задержани\w*|"
    r"может\s+быть\s+(?:задержан\w*|арестован\w*)|"
    r"не\s+(?:был\s+)?(?:задержан\w*|арестован\w*))\b", re.I
)
ANNOUNCER = re.compile(r"\b(?:объяснил\w*|прокомментировал\w*|рассказал\w*|заявил\w*|сообщил\w*)\b", re.I)
NAME_PAIR = re.compile(r"\b([А-ЯЁ][а-яё]+)\s+([А-ЯЁ][а-яё]+(?:-[А-ЯЁ][а-яё]+)?)\b")
NOT_NAME = {"мурманской", "вологодской", "ленинградской", "архангельской",
            "псковской", "новгородской", "калининградской", "санкт",
            "республики", "следственный", "следственного", "комитета", "россии",
            "области", "российской", "правительства", "генеральной", "сотрудниками"}


def first_lead(summary, limit=450):
    txt = re.sub(r"\s+", " ", summary or "").strip()
    # Первые две фразы: источник подтверждения часто во второй.
    parts = re.split(r"(?<=[.!?])\s+", txt)
    return " ".join(parts[:2])[:limit]


def _role_anchor(text):
    """Роль связана с действием, а регион — с должностью, не со СМИ."""
    for match in ROLE.finditer(text):
        before = text[max(0, match.start()-65):match.start()]
        if FORMER.search(before):
            continue
        after = text[match.end():match.end()+100]
        near_role = text[max(0, match.start()-80):match.end()+100]
        if not REGION_CUE.search(near_role):
            continue
        # «министр РФ», «губернатор сообщил, что задержали директора» — не цель.
        federal = re.search(r"\b(?:России|РФ|федеральн\w*)\b", after[:70], re.I)
        if federal and (not REGION_CUE.search(after[:federal.start()]) or
                        match.group().lower().startswith(("министр", "зам", "перв"))):
            continue
        # Министры и их заместители должны быть идентифицированы как
        # региональные, а не просто задержанные *на территории* региона.
        if re.search(r"(?:^|\s)(?:зам(?:естител\w*)?\s+)?министр", match.group(), re.I):
            if not REGION_CUE.search(after[:80]):
                continue
        yield match


def _stage_for(text):
    for stage, pat in STAGES:
        for action in pat.finditer(text):
            for role in _role_anchor(text):
                distance = min(abs(action.start()-role.end()), abs(role.start()-action.end()))
                if distance > 155:
                    continue
                between = text[min(action.end(), role.end()):max(action.start(), role.start())]
                # Сравниваем утверждение об участнике, а не новость, которую
                # упомянул чиновник. Между двумя словами не должно быть
                # перехода в другое предложение или глагола пересказа.
                if "." in between or "!" in between or "?" in between:
                    continue
                if role.start() < action.start() and ANNOUNCER.search(between):
                    continue
                return stage, role
    return None


def _subject_near_role(text, role):
    # Имя после должности («губернатор Мурманской области Андрей Чибис»).
    # Общий extract_person() исключает имена губернаторов как назначающих,
    # поэтому для процессуальных событий нужен свой узкий извлекатель.
    context = text[role.end():role.end()+100]
    context = re.split(r"[.!?;]", context)[0]
    for pair in NAME_PAIR.finditer(context):
        if pair.group(1).lower() in NOT_NAME or pair.group(2).lower() in NOT_NAME:
            continue
        if ANNOUNCER.search(context[:pair.start()]):
            continue
        return pair.group(0)
    return ""


def detect_proceedings(title, summary):
    """Возвращает событие либо None; юридические выводы не делает."""
    title = re.sub(r"\s+", " ", title or "").strip()
    lead = first_lead(summary)
    text = (title + ". " + lead).strip()
    if UNCONFIRMED.search(text) or title.endswith("?"):
        return None
    if not AUTHORITY.search(text) or not OFFICIAL_REPORT.search(text):
        return None
    found_title = _stage_for(title)
    found = found_title or _stage_for(lead)
    if not found:
        return None
    stage, role = found
    subject = _subject_near_role(title if found_title else lead, role)
    return {
        "type": "proceeding", "level": "deputy" if re.search(r"\b(?:зам|вице)", role.group(), re.I) else "head",
        "org_class": "gov", "orgs": [], "stage": stage, "subject": subject,
    }
