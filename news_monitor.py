def notify():
    import notify_telegram as nt
    token = os.environ.get("TELEGRAM_BOT_TOKEN", "").strip()
    chat_ids = [c.strip() for c in os.environ.get("TELEGRAM_CHAT_ID", "").split(",") if c.strip()]
    if not token or not chat_ids:
        print("Telegram не настроен — пропускаю.")
        return 0
    summary = load_json(RUN_SUMMARY, {})
    new = summary.get("new", [])
    if not new:
        print("Новых событий нет — уведомление не нужно.")
        return 0
    base = nt.site_url()
    by_region = {}
    for ev in new:
        by_region.setdefault(ev["region"], []).append(ev)
    icon = {"appointment": "👤", "leave": "🚪", "title": "🎖", "obituary": "🕯", "visit": "🏛", "anniversary": "🎂",
            "launch": "🚀", "award": "🏅", "status": "⭐", "ownership": "🏦", "workforce": "👥", "proceeding": "⚖️"}
    lines = [f"📰 <b>{esc(STREAM_FULL_NAME)}</b> — {len(new)} "
             f"{nt.plural(len(new), 'новое событие', 'новых события', 'новых событий')}"]
    for region in sorted(by_region, key=lambda r: g.REGION_ORDER.index(r) if r in g.REGION_ORDER else 99):
        lines.append(f"\n<b>{esc(region)}</b>")
        for ev in by_region[region]:
            title = ev["title"].strip()
            if len(title) > 160:
                cut = title.rfind(" ", 40, 159)
                title = title[:cut if cut > 0 else 159].rstrip(" ,;:—-") + "…"
            lines.append(f"{icon.get(ev['type'], '•')} <a href=\"{esc(ev['link'])}\">{esc(title)}</a>"
                         f" <i>({esc(ev['source'])})</i>")
    if base:
        lines.append(f'\n<a href="{esc(base)}news.html">Все события →</a>')
    text = "\n".join(lines)
    messages, cur = [], ""
    for line in text.split("\n"):
        if len(cur) + len(line) + 1 > nt.TG_LIMIT - 50:
            messages.append(cur)
            cur = ""
        cur += line + "\n"
    messages.append(cur)
    # A repeated --notify on the same checkout must not resend a delivered
    # message. The receipt is kept in the existing summary (no new file).
    # Hash the bot token and chat ID together: never publish either value.
    content_id = hashlib.sha256("\n".join(messages).encode("utf-8")).hexdigest()
    delivery = summary.get("notify_delivery", {})
    if delivery.get("digest") != content_id:
        delivery = {"digest": content_id, "completed": {}}
    completed = delivery.setdefault("completed", {})
    report = {}
    failed = False
    for chat in chat_ids:
        recipient = hashlib.sha256(f"{token}:{chat}".encode("utf-8")).hexdigest()[:24]
        next_message = min(int(completed.get(recipient, 0)), len(messages))
        for idx in range(next_message, len(messages)):
            success = nt.send(token, [chat], messages[idx].strip(), report)
            if success is False:
                failed = True
                break
            # The real sender returns bool. Test stubs may return None; do
            # not write to production files while running legacy tests.
            if success is True:
                completed[recipient] = idx + 1
                summary["notify_delivery"] = delivery
                save_json(RUN_SUMMARY, summary)
    if report:
        nt.print_report(report)
    if not failed and not report and all(
        int(completed.get(hashlib.sha256(f"{token}:{chat}".encode("utf-8")).hexdigest()[:24], 0))
        >= len(messages) for chat in chat_ids
    ):
        print("Telegram: это сообщение уже отправлено всем получателям.")
    if failed:
        # Недоступные личные чаты не должны делать весь сбор новостей красным,
        # когда дайджест действительно доставлен другим адресатам.
        # Канал/группа (отрицательный chat_id) остаётся обязательным адресатом:
        # её сбой или отсутствие хотя бы одной полной доставки — ошибка.
        failed_chats = [chat for chat, (ok, _info) in report.items() if not ok]
        if any(chat.startswith("-") for chat in failed_chats):
            print("::error::Telegram: не доставлено в канал или группу; проверьте права бота.")
            return 1
        fully_delivered = any(
            int(completed.get(hashlib.sha256(f"{token}:{chat}".encode("utf-8")).hexdigest()[:24], 0))
            >= len(messages) for chat in chat_ids
        )
        if not fully_delivered:
            print("::error::Telegram: ни один получатель не получил полный дайджест.")
            return 1
        print(f"::warning::Telegram: {len(failed_chats)} личных чатов недоступны; "
              "проверьте /start и TELEGRAM_CHAT_ID. Доставленные сообщения не повторяем.")
    return 0



