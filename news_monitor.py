def title_stems(title):
    words = re.findall(r"[а-яёa-z][а-яёa-z-]{3,}", expand_abbrev(normalize(title)).lower().replace("ё", "е"))
    return {w[:5] for w in words if w not in POS_STOP}


def similar(a, b):
    """Два заголовка об одном событии: регион и тип совпадают, даты рядом, общих основ слов не меньше половины."""
    family = {"appointment", "leave"}
    if a["region"] != b["region"] or (a["type"] != b["type"] and not {a["type"], b["type"]} <= family):
        return False
    try:
        if abs((date.fromisoformat(a["date"]) - date.fromisoformat(b["date"])).days) > 3:
            return False
    except ValueError:
        return False
    if name_pairs(a["title"]) & name_pairs(b["title"]):      # одно «Имя Фамилия» (в любом падеже) в обоих заголовках
        return True
    # заголовок без фамилии («сменился глава комитета по информатизации») целиком раскрыт в тексте другой новости
    for x, y in ((a, b), (b, a)):
        spec = title_stems(x["title"]) - GENERIC_STEMS
        if len(spec) >= 2 and y.get("summary") and spec <= title_stems(y["title"] + " " + y["summary"][:500]):
            return True
    if a["type"] != b["type"]:
        return False
    sa, sb = title_stems(a["title"]), title_stems(b["title"])
    if len(sa) < 2 or len(sb) < 2:
        return False
    common = len(sa & sb)
    return common / min(len(sa), len(sb)) >= 0.5


def event_keys(ev):
    keys = [event_key(ev)]
    pk = position_key(ev)
    if pk:
        keys.append(pk)
    return keys


def event_key(ev):
    person = ev.get("person", "")
    if ev["type"] in ("visit", "anniversary", "launch", "award", "status", "ownership") and ev.get("orgs"):
        return f"{ev['type']}:{ev['region']}:{ev['orgs'][0].lower()}:{ev['date'][:7]}"
    if person:
        return f"{ev['type']}:{surname(person)}"
    norm = re.sub(r"[^а-яёa-z0-9 ]", "", ev["title"].lower())
    return f"{ev['type']}:{norm[:70]}"


APPOINTER_FORM = re.compile(r"\b(?:назначил[аи]?|представил[аи]?|сформировал[аи]?|перераспредел\w+|утвердил[аи]?|"
                            r"освободил[аи]?|отправил[аи]?\s+в\s+отставку|сменил[аи]?)\b", re.I)


def priority(ev):
    """Порядок выбора записи среди дублей: авторитет источника; затем заголовок о назначенном
    («Фаламеева назначена министром») раньше заголовка о назначившем («Филимонов назначил министра»);
    затем заголовок с фамилией; затем дата."""
    return (ev.get("rank", 3), 1 if APPOINTER_FORM.search(ev["title"]) else 0,
            0 if ev.get("person") else 1, ev.get("date", ""))


def reconcile(events, cfg):
    """Перепроверить сохранённые события по текущим правилам: убрать то, что детектор
    больше не считает событием, и склеить дубли, оставив самый авторитетный источник.
    Вызывается при каждом прогоне и при --rebuild, чтобы правки правил применялись
    и к уже найденному. Возвращает (events, seen_keys)."""
    organizations = cfg.get("organizations", {})
    ranks = {src["id"]: src.get("rank", 3) for src in cfg.get("sources", [])}
    srcs = {src["id"]: src for src in cfg.get("sources", [])}
    kept, seen = [], {}
    for ev in events:
        ev["title"] = DATE_WORDS.sub("", ev["title"]).strip()
        if len(ev["title"]) > 140:                       # заголовок, слипшийся с аннотацией (старые прогоны)
            ev["title"], tail = split_anchor(html_module.escape(ev["title"]))
            ev["title"] = html_module.unescape(ev["title"])
            if tail and not ev.get("summary"):
                ev["summary"] = html_module.unescape(tail)
        ev["rank"] = ranks.get(ev.get("source_id"), ev.get("rank", 3))
        ev["person"] = ev.get("person") or extract_person(ev["title"])
    for ev in sorted(events, key=priority):
        det = detect_all(ev["title"], ev.get("summary", ""), organizations)
        if not det:
            continue
        ev["type"], ev["level"], ev["org_class"] = det["type"], det["level"], det["org_class"]
        src = srcs.get(ev.get("source_id"), {"region": ev.get("region")})
        region = attribute_region(src, ev["title"] + " " + ev.get("summary", "")[:300], det["orgs"])
        if not region:
            continue
        ev["region"] = region
        keys = event_keys(ev)
        if any(k in seen for k in keys) or any(similar(ev, e) for e in kept):
            continue
        for k in keys:
            seen[k] = ev["date"]
        kept.append(ev)
    return kept, seen


def run(today=None, verbose=True):
    cfg = load_json(SOURCES_FILE, {"sources": [], "organizations": {}})
    organizations = cfg.get("organizations", {})
    feeds_cache = load_json(FEEDS_CACHE, {})
    today = today or g.msk_today()
    events, seen_from_events = reconcile(load_json(EVENTS_FILE, []), cfg)
    seen = load_json(SEEN_FILE, {})
    seen.update(seen_from_events)
    fresh_from = today - timedelta(days=FRESH_DAYS)

    candidates, statuses = [], []
    for src in cfg["sources"]:
        if not src.get("enabled", True):
            continue
        t0 = time.time()
        items, status = fetch_source(src, feeds_cache)
        statuses.append((src["id"], src["name"], status, round(time.time() - t0, 1)))
        if verbose:
            print(f"  {src['id']:<16} {status:<40} {time.time() - t0:4.1f}s", flush=True)
        for it in items:
            d = parse_date(it.get("date"))
            if d and d < fresh_from:
                continue
            det = detect_all(it["title"], it.get("summary", ""), organizations)
            if not det:
                continue
            text = f"{it['title']} {it.get('summary', '')}"
            region = attribute_region(src, text, det["orgs"])
            if not region:
                continue
            ev = {"type": det["type"], "level": det["level"], "org_class": det["org_class"],
                  "region": region, "title": normalize(it["title"]).strip(), "summary": normalize(it.get("summary", ""))[:400],
                  "link": it.get("link", ""), "date": (d or today).isoformat(),
                  "source": src["name"], "source_id": src["id"], "rank": src.get("rank", 3),
                  "person": extract_person(it["title"]) or extract_person(it.get("summary", "")[:300]),
                  "orgs": sorted({o[1] for o in det["orgs"]})}
            candidates.append(ev)

    # одно событие — одна запись: сначала самый авторитетный источник, остальные склеиваются
    candidates.sort(key=priority)
    new_events = []
    recent = [e for e in events if e.get("date", "") >= (today - timedelta(days=4)).isoformat()]
    for ev in candidates:
        keys = event_keys(ev)
        match = next((e for e in recent + new_events if similar(ev, e) or set(keys) & set(event_keys(e))), None)
        if match is not None:
            # то же событие уже есть; если новый источник авторитетнее — заменяем запись, не уведомляя повторно
            if priority(ev) < priority(match) and match not in new_events:
                ev["upgraded"] = True
                ev["date"] = min(ev["date"], match["date"])
                events.remove(match)
                recent.remove(match)
                new_events.append(ev)
            elif priority(ev) < priority(match):
                new_events[new_events.index(match)] = ev
            for k in keys:
                seen[k] = today.isoformat()
            continue
        if any(k in seen for k in keys):
            continue
        for k in keys:
            seen[k] = today.isoformat()
        new_events.append(ev)
    fresh_new = [e for e in new_events if not e.pop("upgraded", False)]

    # ── сохранить ──
    cutoff = (today - timedelta(days=KEEP_EVENTS_DAYS)).isoformat()
    events = [e for e in events if e.get("date", "") >= cutoff] + new_events
    events.sort(key=lambda e: (e["date"], e["region"], e["title"]), reverse=True)
    seen_cut = (today - timedelta(days=KEEP_SEEN_DAYS)).isoformat()
    seen = {k: v for k, v in seen.items() if v >= seen_cut}
    save_json(EVENTS_FILE, events)
    save_json(SEEN_FILE, seen)
    save_json(FEEDS_CACHE, feeds_cache)
    errors = [s for s in statuses if s[2].startswith("error")]
    save_json(RUN_SUMMARY, {"date": today.isoformat(), "new": fresh_new,
                            "sources_total": len(statuses), "sources_failed": len(errors),
                            "failed": [{"id": s[0], "name": s[1], "status": s[2]} for s in errors]})
    render_page(events, today)
    if verbose:
        print(f"\nИсточников: {len(statuses)}, с ошибкой: {len(errors)}; новых событий: {len(fresh_new)}")
        for ev in fresh_new:
            print(f"  [{ev['type']}/{ev['level']}] {ev['region']}: {ev['title'][:100]}")
    return fresh_new, statuses


def check_sources():
    cfg = load_json(SOURCES_FILE, {"sources": []})
    feeds_cache = {}
    rows, ok = [], 0
    print(f"{'id':<16} {'тип':<9} {'статус':<48} {'сек':>5}  источник")
    for src in cfg["sources"]:
        if not src.get("enabled", True):
            print(f"{src['id']:<16} {src['type']:<9} {'выключен':<48} {'':>5}  {src['name']}")
            continue
        t0 = time.time()
        items, status = fetch_source(src, feeds_cache)
        dt = time.time() - t0
        if not status.startswith("error"):
            ok += 1
        sample = items[0]["title"][:70] if items else ""
        print(f"{src['id']:<16} {src['type']:<9} {status[:48]:<48} {dt:5.1f}  {src['name']}"
              + (f"\n{'':<16} {'':<9} пример: {sample}" if sample else ""), flush=True)
        rows.append((src, status))
    print(f"\nДоступно {ok} из {len(rows)} источников.")
    bad = [s for s, st in rows if st.startswith("error")]
    if bad:
        print("Недоступны:", ", ".join(s["id"] for s in bad))
    return rows


