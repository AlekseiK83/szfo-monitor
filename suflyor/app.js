const Store = (()=>{
  let dbp = null;
  function open(){
    if(dbp) return dbp;
    dbp = new Promise((res, rej)=>{
      if(!('indexedDB' in window)){ rej(new Error('IndexedDB недоступна')); return; }
      const r = indexedDB.open('suflyor', 1);
      r.onupgradeneeded = ()=>{
        const d = r.result;
        if(!d.objectStoreNames.contains('sessions')) d.createObjectStore('sessions', {keyPath:'id'});
        if(!d.objectStoreNames.contains('audio')) d.createObjectStore('audio', {keyPath:'id'});
        if(!d.objectStoreNames.contains('kv')) d.createObjectStore('kv', {keyPath:'k'});
      };
      r.onsuccess = ()=>res(r.result);
      r.onerror = ()=>rej(r.error);
    });
    return dbp;
  }
  function tx(store, mode, fn){
    return open().then(d=>new Promise((res, rej)=>{
      const t = d.transaction(store, mode); const s = t.objectStore(store);
      let out; const r = fn(s); if(r) r.onsuccess = ()=>{ out = r.result; };
      t.oncomplete = ()=>res(out); t.onerror = ()=>rej(t.error); t.onabort = ()=>rej(t.error);
    }));
  }
  return {
    get:(st,k)=>tx(st,'readonly',s=>s.get(k)),
    put:(st,v)=>tx(st,'readwrite',s=>s.put(v)),
    del:(st,k)=>tx(st,'readwrite',s=>s.delete(k)),
    all:(st)=>tx(st,'readonly',s=>s.getAll()),
    clear:(st)=>tx(st,'readwrite',s=>s.clear()),
    kv: async (k, v)=>{ if(v===undefined){ const r = await tx('kv','readonly',s=>s.get(k)); return r ? r.v : undefined; } return tx('kv','readwrite',s=>s.put({k, v})); }
  };
})();

