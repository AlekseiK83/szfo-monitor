def detect(title, summary, organizations):
    """Возвращает описание события или None.

    {"type": "appointment"|"title"|"leave", "level": "head"|"deputy",
     "org_class": ..., "orgs": [...], "hints": [...]}"""
    title = normalize(title)
    summary = normalize(summary or "")
    text = f"{title}\n{summary}"
    head = title + " " + summary[:300]            # должность и организация — заголовок и начало текста
    lead = title + " " + first_sentence(summary)  # глагол события — только заголовок и первая фраза

    if UNCERTAIN.search(head) or NOT_OUR_SCOPE.search(head):
        return None
    # «Компания возглавила рейтинг» — не кадровое назначение.
    if re.search(r"\bвозглавил[аи]?\s+(?:рейтинг|топ|список|таблиц|перечень)\w*\b", title, re.I):
        return None
    # Массовый набор специалистов рассматривает только детектор workforce:
    # случайная должность губернатора/министра в лиде не создаёт назначение.
    if MASS_STAFF_HEADLINE.search(title) and not EXECUTIVE_CHANGE_IN_TITLE.search(title):
        return None

    orgs = find_org_names(text, organizations)
    org_class = classify_org(head)

    # ── Звание ──
    tv_title = TITLE_VERB.search(title)
    tv = tv_title or TITLE_VERB.search(first_sentence(summary))
    # Не превращать новость о пособиях/пенсиях в новое награждение только
    # потому, что в её аннотации сказано «ранее присвоено звание».
    historical_benefits = bool(SOCIAL_BENEFITS_HEADLINE.search(title) and not tv_title)
    if tv and not historical_benefits and TITLE_NOUN.search(head) and not NAME_GIVING.search(head) \
            and (not WEAK_TITLE_VERB.fullmatch(tv.group(0)) or STRONG_TITLE_NOUN.search(head)):
        # Должность комментатора из другой фразы аннотации — не должность
        # человека, которому присваивают звание.
        award_clause = title if tv_title else title + " " + first_sentence(summary)
        if CORE_TITLE.search(head) or POSITION.search(award_clause):
            return {"type": "title", "level": "head", "org_class": org_class or "person", "orgs": orgs}
        return None

    # ── Назначение / уход ──
    if CRIMINAL.search(head) and COURT_ROUTINE.search(head):      # «бывшего главврача освободили из-под стражи»
        return None
    if re.search(r"назнач\w+\s+(?:ему|ей|им)?\s*(?:\d+\s*(?:лет|год|месяц)|реальн|условн|срок|наказан|штраф|дат[аыуые]|проверк|экспертиз|выплат|пособ|пенси)", lead, re.I) \
            or re.search(r"\bсуд\w*\s+(?:назначил|приговорил|вынес|признал|оштрафовал)", lead, re.I):
        return None
    has_pos = POSITION.search(head)
    appoint = APPOINT_VERB.search(lead) or (BECOME.search(lead) and INSTRUMENTAL.search(lead))
    if HEAD_VERB.search(lead):
        appoint, has_pos = True, True
    if not has_pos:
        return None
    leave = LEAVE_VERB.search(lead) or GOVERNOR_REMOVAL.search(title)
    if not appoint and not leave:
        return None
    # «Врио станет один из замов» — предварительное предположение, а не
    # подтверждённый выбор конкретного руководителя.
    if appoint and UNNAMED_GOVERNOR_FORECAST.search(title):
        return None
    if not org_class and not orgs:
        return None
    if DISTRICT_HEAD.search(head) and not re.search(r"петербург|спб", head, re.I):
        return None
    # Предмет назначения определяет заголовок; лицо, представлявшее нового
    # начальника в аннотации (замминистра, первый зампред), не меняет его уровень.
    role_text = title if (POSITION.search(title) or INSTRUMENTAL.search(title) or HEAD_VERB.search(title)) else lead
    level = "deputy" if DEPUTY.search(role_text) else "head"
    etype = "appointment" if appoint else "leave"
    return {"type": etype, "level": level, "org_class": org_class or "company", "orgs": orgs}


def detect_extra(title, summary, organizations, region_hint=None):
    """Инфоповоды по ключевым учреждениям и компаниям (кроме назначений и званий).

    Срабатывает, только если организация известна (словарь organizations) или это
    орган власти / силовое ведомство / областное учреждение, а для визитов — первое лицо."""
    title = normalize(title)
    summary = normalize(summary or "")
    head = title + " " + summary[:300]
    lead = title + " " + first_sentence(summary)
    if UNCERTAIN_EXTRA.search(lead) or NOT_OUR_SCOPE.search(lead):
        return None
    orgs = find_org_names(head, organizations)
    org_class = classify_org(head)
    known = bool(orgs) or org_class in ("gov", "force", "podved")
    has_pos = POSITION.search(head)

    # 1. Смерть руководителя или известного лица, связанного с учреждением
    if OBITUARY.search(lead) and ((has_pos and (known or org_class)) or TITLE_NOUN.search(head)) \
            and not (re.search(r"\b(?:бывш\w+|экс-|ветеран\w*|пенсионер\w*|в\s+прошлом|почётн\w+\s+работник|заслуженн\w+\s+(?:работник|строител|врач|учител|юрист|экономист|энергетик|машиностроител|деятел)\w*\s+(?:РФ|России))", head, re.I)
                     and not CORE_TITLE.search(head) and not orgs):      # бывший глава Севмаша — да, бывший управляющий трестом — нет
        return {"type": "obituary", "level": "head", "org_class": org_class or "person", "orgs": orgs}

    # 2. Визит первого лица в регион / на предприятие
    vm, vv = VISIT.search(head), VISIT_VERB.search(head)
    if vm and vv and vm.start() < vv.start() and not re.search(r"\b(?:о|об|про|памяти|посвящ\w+|служени\w+|выставк\w*|концерт\w*|фестивал\w*|книг\w*|фильм\w*|спектакл\w*)\b[^.]{0,40}$", head[:vm.start()], re.I) \
            and not re.search(r"\b(?:выставк|концерт|фестивал|служени|богослужени|литурги|молебен|премьер\w+\s+(?:спектакл|фильм))", head, re.I) \
            and (orgs or org_class in ("business", "podved", "force") or LAUNCH_SCALE.search(head)):
        return {"type": "visit", "level": "head", "org_class": org_class or "company", "orgs": orgs}

    # 3. Круглый юбилей организации (25, 30, 40, 50 … лет)
    am = ANNIVERSARY.search(lead)
    if am and ANNIVERSARY_CTX.search(head) and known and not PERSON_ANNIV.search(lead) and not HISTORIC_ANNIV.search(head) \
            and not re.search(r"\b(?:фестивал\w*|концерт\w*|шоу|квест\w*|праздничн\w*\s+конкурс\w*)\b", title, re.I) \
            and not re.search(r"\b(?:военн\w+\s+оркестр\w*|оркестр\w*\s+(?:штаба|военн\w+)|оркестр\w*\s+Росгварди\w*)\b", title, re.I) \
            and not re.search(r"^(?:режисс[её]р|акт[её]р|артист|писатель|художник|музыкант|певец|певица|драматург)\b.{0,95}\b(?:отмечает|отметил|празднует|исполнилось|исполняется)\b", title, re.I) \
            and not (has_pos and re.search(r"\b(?:отметил[аи]?|отпраздновал[аи]?|празднует|исполнилось|исполняется)\b", lead, re.I)):
        n = int(am.group(1))
        if n >= 25 and n % 5 == 0 and not re.search(r"\bлет(?:ие|ия|ию)?\s+(?:со\s+дня\s+рождения|\S+\s+\S+(?:ич|вн)[ауе]?\b)", head, re.I) \
                and not re.search(r"\bлет\s+назад", head, re.I):
            return {"type": "anniversary", "level": "head", "org_class": org_class or "company", "orgs": orgs}

    # 4. Запуск крупного объекта, спуск судна, ввод в эксплуатацию, крупный контракт
    lm = LAUNCH.search(title) or (LAUNCH.search(lead) and LAUNCH_TITLE_NOUN.search(title))
    # Договор о взаимодействии — не ввод объекта и не инвестконтракт.
    if COOPERATION_ONLY.search(title):
        lm = None
    # «Запуск своего дела» = субсидия/предпринимательство, не открытие
    # инфраструктурного объекта; само упоминание крупной суммы не основание.
    if re.search(r"(?:на\s+запуск\s+(?:своего|собственного)\s+дела|"
                 r"(?:смогут|может|планиру\w*)\s+получить[^.]{0,90}?\b(?:рубл|миллион)|"
                 r"на\s+открытие\s+(?:своего|собственного)\s+(?:дела|бизнеса))", title, re.I):
        lm = None
    if lm and (re.search(r"\d+\s*%|процент|больше,?\s+чем|меньше,?\s+чем|снизил|сократил|вырос|упал|закрыл", title, re.I)
               or not (LAUNCH_OBJECT.search(title) or LAUNCH_SCALE.search(title) or LAUNCH_TITLE_NOUN.search(title))):
        lm = None                                      # «закрылось на 39 % больше, чем открылось» — статистика, не запуск
    # для компаний из базы достаточно предмета запуска (производство, судно, линия, контракт на строительство)
    strong_launch = bool(lm and orgs and LAUNCH_OBJECT.search(head)
                         and not re.search(r"\b(?:программ|акци[юия]|сотрудничеств|партн[её]рств|сервис|приложени|конкурс|набор|вакансi|выставк)", head, re.I))
    if lm and (strong_launch or LAUNCH_SCALE.search(head)) and (orgs or org_class in ("business", "podved", "gov")) \
            and not re.search(r"\b(?:ремонт|благоустро|сквер|детск\w+\s+площадк|выставк|фестивал|ярмарк|сезон|навигаци|"
                              r"в\s+сел[ео]|в\s+деревн|в\s+пос[её]лке|сельск|каток|катк[аеу]|котельн|ФАП\b|фельдшерск|"
                              r"сформирован\w*\s+(?:план|перечень)|план\w*\s+по\b|дорожн\w+\s+карт)", head, re.I):
        return {"type": "launch", "level": "head", "org_class": org_class or "company", "orgs": orgs}

    # 5. Государственная или региональная награда организации либо её руководителю
    if ORG_AWARD.search(lead) and ORG_AWARD_NOUN.search(head) and orgs:
        return {"type": "award", "level": "head", "org_class": org_class or "company", "orgs": orgs}

    # 6. Федеральный статус, рейтинг, победа во всероссийском конкурсе
    if STATUS.search(lead) and not MEDIA_SELF.search(head) and not CONSUMER_RATING.search(head) \
            and not re.search(r"^(?:сотрудник|команд|работник|специалист|студент|школьник|учени|воспитанник|врач[иа]\b|спортсмен)", lead, re.I) and (orgs or (org_class in ("podved", "business", "gov")
                                         and re.search(r"\b(?:всероссийск|федеральн|национальн|России|стран[ыеу]|международн)", head, re.I))):
        return {"type": "status", "level": "head", "org_class": org_class or "company", "orgs": orgs}

    # 7. Смена собственника, банкротство, уголовное преследование руководства — только для компаний из словаря
    om = OWNERSHIP.search(lead)
    if om and orgs:
        criminal = CRIMINAL.search(om.group(0)) is not None
        # судебная рутина прокуратуры (приговоры, гособвинение, дела бывших чиновников) — не кадровое событие
        if criminal and COURT_ROUTINE.search(lead):
            return None
        if criminal and org_class == "business" and not orgs:   # «глава турфирмы», «директор ООО» без имени в базе — не наш уровень
            return None
        if not criminal or has_pos:        # «задержан гендиректор» — да, «возбудили дело после ДТП» — нет
            return {"type": "ownership", "level": "head", "org_class": org_class or "company", "orgs": orgs}
    return None


# Судебное назначение арбитражного управляющего в процедуре банкротства —
