def news_region(text):
    """Регион СЗФО по тексту новости. Побеждает самое раннее упоминание;
    при явном чужом регионе — None (как в generate.match_region)."""
    if not text or g._has_foreign_region(text) or local_context_foreign_matches(text):
        return None
    best = None
    for name, _slug, patterns in g.SZFO_COMPILED:
        for p in patterns:
            m = p.search(text)
            if m and (best is None or m.start() < best[0]):
                best = (m.start(), name)
    for name, patterns in _NEWS_REGION_COMPILED:
        for p in patterns:
            m = p.search(text)
            if m and (best is None or m.start() < best[0]):
                best = (m.start(), name)
    if best:
        # регион учреждения («правительства Карелии», «УМВД по Коми») важнее региона происхождения («из Вологодской области»)
        for name, _slug, patterns in g.SZFO_COMPILED:
            for p in patterns:
                for m in p.finditer(text):
                    before = text[max(0, m.start() - 60):m.start()]
                    if REGION_INSTITUTION.search(before) and not re.search(r"\bиз\s*$", before, re.I):
                        return name
    return best[1] if best else None


def attribute_region(src, text, orgs):
    """Регион события: по тексту → по словарю организаций → по источнику."""
    from_text = news_region(text)
    if from_text:
        return from_text
    if orgs:
        return orgs[0][0]
    if src.get("region") and not src.get("region_from_text"):
        if g._has_foreign_region(text) or local_context_foreign_matches(text):   # региональное СМИ пишет о чужом регионе
            return None
        return src["region"]
    return None


