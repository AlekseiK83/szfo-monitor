# Для процессуальных новостей три формы заголовка часто описывают одну стадию:
# «задержан губернатор Иванов», «подтвердили задержание губернатора»,
# «задержание областного губернатора Иванова». Имя не обязательно присутствует
# во всех лентах. Сопоставляем должность только там, где она уникальна в регионе.
PROCEEDING_GOVERNOR = re.compile(r"\bгубернатор[а-яё]*\b", re.I)
PROCEEDING_DEPUTY_BEFORE = re.compile(
    r"(?:вице[-\s]?|зам(?:естител[а-яё]*)?\s+|перв[а-яё]*\s+заместител[а-яё]*\s+)$", re.I)
PROCEEDING_REGION_AFTER_ROLE = re.compile(
    r"^(?:(?:[А-ЯЁ][а-яё-]+\s+(?:области|края|округа))|"
    r"(?:Республики\s+[А-ЯЁ][а-яё-]+)|"
    r"(?:Санкт-Петербурга|Петербурга|Карелии|Коми))\s+"
)
PROCEEDING_NON_NAMES = {
    "сообщил", "сообщила", "подтвердил", "подтвердила", "задержан",
    "задержали", "арестован", "арестовали", "обвинен", "обвинён",
    "под", "после", "как", "из", "области", "республики", "страны"
}


def proceeding_office(ev):
    """Возвращает только гарантированно единственную должность в субъекте РФ.

    Заместители губернатора и региональные министры здесь намеренно не
    склеиваются по одному названию должности: одновременно их может быть много.
    """
    if ev.get("type") != "proceeding" or ev.get("level") == "deputy":
        return ""
    text = ev.get("title", "") + " " + ev.get("summary", "")[:240]
    for match in PROCEEDING_GOVERNOR.finditer(text):
        before = text[max(0, match.start() - 45):match.start()]
        if PROCEEDING_DEPUTY_BEFORE.search(before):
            continue
        return "governor"
    return ""


PROCEEDING_NON_PERSON = {
    "он", "она", "они", "его", "ее", "её", "ему", "ней", "после", "по",
    "области", "региона", "республики", "края", "суд", "полиция",
    "сообщил", "сообщила", "подтвердил", "подтвердила", "вслед",
    "путин", "мишустин", "президент",
}


def proceeding_subject(ev):
    """Основа фамилии действующего лица, если упомянута рядом с должностью.

    В лентах возможны «Андрей Чибис» и «губернатора Чибиса». Ищем фамилию
    после роли, если основной детектор не заполнил ev['person'].
    """
    person = ev.get("person", "").strip()
    if person:
        identity = surname(person)
        if (identity and len(identity) >= 4 and identity not in PROCEEDING_NON_PERSON
                and identity not in {"путин", "мишустин", "президент"}):
            return identity
    text = ev.get("title", "") + " " + ev.get("summary", "")[:180]
    for match in PROCEEDING_GOVERNOR.finditer(text):
        after = text[match.end():match.end() + 105].lstrip()
        after = PROCEEDING_REGION_AFTER_ROLE.sub("", after)
        pair = re.match(r"([А-ЯЁ][а-яё-]+)(?:\s+([А-ЯЁ][а-яё-]+))?", after)
        if not pair:
            continue
        words = [part for part in pair.groups() if part]
        if words and words[0].lower() not in (PROCEEDING_NON_NAMES | PROCEEDING_NON_PERSON):
            last = name_stem(words[-1])
            if last not in PROCEEDING_NON_PERSON:
                return last
    return ""


def same_proceeding(a, b):
    """Одна стадия одного процессуального события, независимо от СМИ/URL.

    Наличие имени хотя бы в одном заголовке не мешает объединить заметку
    без имени о *той же уникальной должности*. Разные названные лица не
    объединяем. Не объединяем события разных процессуальных стадий.
    """
    if a.get("type") != "proceeding" or b.get("type") != "proceeding":
        return False
    if a.get("region") != b.get("region") or a.get("procedure_stage") != b.get("procedure_stage"):
        return False
    try:
        if abs((date.fromisoformat(a["date"]) - date.fromisoformat(b["date"])).days) > 7:
            return False
    except (KeyError, ValueError, TypeError):
        return False
    pa, pb = proceeding_subject(a), proceeding_subject(b)
    if pa and pb:
        return pa == pb
    # Пока есть хотя бы одно сообщение без имени, роль должна быть уникальна:
    # только губернатор конкретного субъекта РФ. Для вице-губернаторов,
    # региональных министров и их заместителей необходимо имя или контекст.
    return proceeding_office(a) == proceeding_office(b) == "governor"



ANNIVERSARY_YEARS = re.compile(r"\b(\d{2,3})\s*(?:-?лети[яеюйм]?|лет\b|годовщи)", re.I)
ANNIVERSARY_WORDS_IGNORE = {"областн", "клинич", "городск", "сегодн", "отмети", "отмеча", "исполн", "праздн", "юбиле", "состо", "своег", "перву"}

def same_organization_anniversary(a, b):
    """Сопоставление ЮБИЛЕЯ одной организации в разных сообщениях.

    Требует тот же регион, тот же возраст (80/100 и т.д.) и устойчивое
    название учреждения. Не склеивает два разных юбилея одной отрасли.
    """
    ma, mb = ANNIVERSARY_YEARS.search(a.get("title", "")), ANNIVERSARY_YEARS.search(b.get("title", ""))
    if not ma or not mb or ma.group(1) != mb.group(1):
        return False
    def core(ev):
        text = expand_abbrev(normalize(ev.get("title", ""))).lower().replace("ё", "е")
        text = re.sub(r"\b\d{2,3}\s*(?:-?лет\w*|годовщин\w*)", " ", text)
        return {w[:6] for w in re.findall(r"[а-я]{5,}", text)
                if w[:6] not in ANNIVERSARY_WORDS_IGNORE and
                not w.startswith(("отмеч", "исполн", "праздн", "прошл", "участ", "предст"))}
    wa, wb = core(a), core(b)
    # Географические прилагательные сами по себе не доказывают,
    # что речь идёт об одной организации.
    institution_kinds = {"больни", "театр", "универ", "музей", "школа", "оркест",
                         "комбин", "завод", "поликл", "инстит", "филарм", "центра"}
    common = wa & wb
    if not common.intersection(institution_kinds) and len(common) < 3:
        return False
    # Одно и то же городское/областное учреждение нельзя склеить лишь
    # потому, что обе публикации упоминают город и слово «больница».
    qualifiers = {"област", "городс", "районн", "детска", "центра", "инфекц",
                  "психиа", "клинич"}
    qa = (wa & qualifiers) - {"клинич"}
    qb = (wb & qualifiers) - {"клинич"}
    if qa != qb:
        return False
    return len(common) >= 2

UNIQUE_FORCE_OFFICE = re.compile(r"\b(?:УФСБ|управлени[яюем]\s+ФСБ|"
                                 r"(?:региональн\w+|областн\w+)\s+управлени[яюем]\s+ФСБ)\b", re.I)

def same_unique_regional_force_office(a, b):
    """Назначен и представлен один руководитель управления ФСБ региона.

    Совпадение допускается без имени в одной публикации только для
    уникальной должности главы управления, но не для заместителей.
    """
    def head_fsb(ev):
        t = (ev.get("title") or "") + " " + (ev.get("summary") or "")[:160]
        if re.search(r"\b(?:заместител[а-яё]*|замначальник[а-яё]*|вице-)\s+(?:\S+\s+){0,3}?(?:УФСБ|управлени[яюем]\s+ФСБ)", t, re.I):
            return False
        if ev.get("level") == "deputy":
            return False
        return bool(UNIQUE_FORCE_OFFICE.search(t) and
                    re.search(r"\b(?:начальник|глав[аоыую]|руководител|возглав|назнач|представил)\w*", t, re.I))
    if not (head_fsb(a) and head_fsb(b) and a.get("type") == b.get("type") == "appointment"):
        return False
    named_a = name_pairs(a.get("title", ""))
    named_b = name_pairs(b.get("title", ""))
    return not (named_a and named_b and not (named_a & named_b))

# Для единственной должности руководителя региона перефразировки с именем
# и без имени должны образовывать одно событие. Не применяем эту эвристику
# к заместителям, министрам и руководителям учреждений (там постов несколько).
REGIONAL_ACTING_HEAD = re.compile(
    r"\b(?:врио|в\.?\s*р\.?\s*и\.?\s*о\.?)\s+(?:глав[ыа]|губернатор\w*|руководител\w*)\s+"
    r"(?:региона|области|края|республики|[А-ЯЁ][а-яё-]+\s+области)\b|"
    r"\bвременн\w*\s+возглав\w*\s+(?:регион|област|республик)\w*\b|"
    r"\b(?:регион|област|республик)\w*\s+временн\w*\s+возглав\w*\b",
    re.I,
)
REGIONAL_GOVERNOR_LEAVE = re.compile(
    r"\bгубернатор\w*\b|\bглав[ыуе]\s+(?:[А-ЯЁ][а-яё-]+\s+)?(?:области|республики|региона|края)\b",
    re.I,
)
UNNAMED_GOVERNOR_FORECAST = re.compile(
    r"\b(?:станет|может\s+стать|предположительно\s+станет)\b.{0,90}?"
    r"\b(?:один|одна|кто[- ]то)\s+из\s+(?:замов|заместител\w*|кандидат\w*)\b",
    re.I,
)


def regional_governor_stage(ev):
    """Только события о смене главы СУБЪЕКТА, не смена городского мэра."""
    title = ev.get("title", "")
    if ev.get("type") == "appointment" and REGIONAL_ACTING_HEAD.search(title):
        # «врио главы города» не равно «врио главы области».
        if re.search(r"\bврио\s+глав[ыа]\s+(?:города|района|муниципал)", title, re.I):
            return ""
        return "acting_governor"
    if ev.get("type") == "leave" and REGIONAL_GOVERNOR_LEAVE.search(title):
        # Упоминание «спецпредставителя губернатора» в сообщении об уходе
        # главы комитета — НЕ отставка самого губернатора.
        governor_is_target = bool(re.search(
            r"\b(?:снял[аи]?|уволил[аи]?|отправил[аи]?\s+в\s+отставку|"
            r"прекратил[аи]?\s+полномочия|освободил[аи]?\s+от\s+должности)"
            # «отправил в отставку ... главу Мурманской области» — та же
            # уникальная должность, что и «губернатора Мурманской области».
            r"[^.!?]{0,100}?\b(?:с\s+поста\s+губернатора|губернатора\s+|"
            r"глав[уа]\s+(?:[А-ЯЁ][а-яё-]+\s+)?(?:области|республики|региона|края)\b)",
            title, re.I))
        governor_is_subject = bool(re.search(
            r"\bгубернатор\w*\b[^.!?]{0,75}?\b(?:уш\w*\s+в\s+отставку|"
            r"освобожд\w*\s+от\s+должности|покинул\w*\s+пост|отправлен\w*\s+в\s+отставку)",
            title, re.I))
        if not (governor_is_target or governor_is_subject):
            return ""
        if re.search(r"\b(?:заместител\w*|замгубернатор\w*|вице[- ]губернатор\w*)\s+"
                     r"(?:[А-ЯЁ][а-яё-]+\s+)?губернатор", title, re.I):
            return ""
        return "governor_departure"
    return ""


def regional_governor_actor(ev, stage):
    """Имя именно участника кадрового решения, без фамилии предшественника.

    Если имя не установлено, сравниваем уникальную должность, но два
    РАЗНЫХ явно названных человека никогда не склеиваем.
    """
    title = ev.get("title", "")
    if stage == "acting_governor":
        # «после ареста Андрея Чибиса» — это не фамилия нового врио;
        # «один из замов Чибиса» — тем более не имя назначенного.
        title = re.split(r"\bпосле\s+(?:ареста|задержания|отставки|увольнения)|"
                         r"\b(?:один|одна)\s+из\s+зам", title, maxsplit=1, flags=re.I)[0]
        names = {last for _first, last in name_pairs(title)}
        for match in re.finditer(
            r"\b([А-ЯЁ][а-яё-]{3,})\s+(?:стал[аи]?\s+врио|"
            r"временн\w*\s+возглав\w*|назначен[аы]?\s+врио)\b|"
            r"\b(?:правительства\s+)?региона\s+([А-ЯЁ][а-яё-]{3,})\s*$", title
        ):
            surname_token = next((v for v in match.groups() if v), "")
            if surname_token and surname_token.lower() not in {"области", "региона", "глава", "главы"}:
                names.add(name_stem(surname_token))
        return names
    # Берём только участника отставки, но не назначившего его президента.
    # После «губернатора Мурманской области» стоит ТОПОНИМ, а не фамилия:
    # именно эту ошибку раньше делал жадный regex («мурманск» вместо Чибиса).
    names = set()
    for role in re.finditer(
        r"\b(?:губернатор[а-яё]*|глав[уа]\s+(?:[А-ЯЁ][а-яё-]+\s+)?"
        r"(?:области|республики|региона|края))\b", title, re.I
    ):
        after = title[role.end():].lstrip()
        # Сначала убираем полное наименование региона, только потом ищем имя.
        after = re.sub(
            r"^(?:(?:[А-ЯЁ][а-яё-]+\s+(?:области|края|округа))|"
            r"(?:Республики\s+[А-ЯЁ][а-яё-]+))\b\s*", "", after
        )
        named = re.match(
            r"([А-ЯЁ][а-яё-]{3,})(?:\s+([А-ЯЁ][а-яё-]{3,}))?\b", after
        )
        if named:
            last = named.group(2) or named.group(1)
            if last.lower() not in {
                "области", "региона", "края", "республики", "мурманской",
                "новгородской", "псковской", "архангельской", "вологодской",
                "ленинградской", "калининградской", "губернатора",
            }:
                names.add(name_stem(last))
    # «Снял Андрея Чибиса с поста губернатора» — имя до должности.
    for match in re.finditer(
        r"\b[А-ЯЁ][а-яё-]{3,}\s+([А-ЯЁ][а-яё-]{3,})\s+"
        r"с\s+поста\s+губернатора\b", title
    ):
        names.add(name_stem(match.group(1)))
    return names


def same_regional_governor_decision(a, b, days_apart):
    if a.get("region") != b.get("region"):
        return False
    stage = regional_governor_stage(a)
    if not stage or stage != regional_governor_stage(b):
        return False
    # Повторные публикации о прекращении полномочий продолжают выходить
    # несколько дней; для врио сохраняем прежний более короткий горизонт.
    if days_apart > (10 if stage == "governor_departure" else 3):
        return False
    pa = regional_governor_actor(a, stage)
    pb = regional_governor_actor(b, stage)
    return not (pa and pb and pa.isdisjoint(pb))


REGIONAL_DEPUTY_GOV = re.compile(
    r"\b(?:вице[- ]?губернатор\w*|заместител\w*\s+губернатор\w*|"
    r"замгубернатор\w*)\b", re.I,
)

# Отдельный ключ нужен потому, что «заместитель губернатора» — не одна
# уникальная должность: у губернатора может быть несколько заместителей.
_DEPUTY_PATRONYMIC = re.compile(r"(?:вич|вна|ична|оглы|кызы)[а-яё]*$", re.I)
_DEPUTY_PERSON_TRIPLE = re.compile(
    r"\b([А-ЯЁ][а-яё-]{2,})\s+([А-ЯЁ][а-яё-]{4,})\s+([А-ЯЁ][а-яё-]{3,})\b"
)
_DEPUTY_SURNAME_WITH_ROLE = re.compile(
    r"\b([А-ЯЁ][а-яё-]{3,})\s+(?:стал[аи]?|назначен[аы]?|"
    r"утвержден[аы]?|утверждён[аы]?)\s+"
    r"(?:новым?\s+|новой\s+)?(?:вице[- ]?губернатор\w*|"
    r"заместител\w*\s+губернатор\w*)\b", re.I
)


def is_regional_deputy_appointment(ev):
    """Подтверждаем тип решения и должность, но НЕ полагаемся на level.

    Старые карточки могут иметь ошибочный level='head'; должность от этого
    не становится другой. Проверяем только саму позицию в новости.
    """
    if ev.get("type") != "appointment":
        return False
    title = ev.get("title", "")
    lead = first_sentence(ev.get("summary", ""), limit=300)
    role_in_title = REGIONAL_DEPUTY_GOV.search(title)
    if role_in_title:
        # «Вице-губернатор Иванова назначила директора» — она назначает,
        # а не становится новым вице-губернатором.
        after = title[role_in_title.end():]
        if (re.search(r"\bназначил[аи]\b", after[:95], re.I)
                and re.search(r"\b(?:директор|министр|начальник|ректор|руководител)",
                              after, re.I)
                and not re.search(r"\b(?:назначен[аы]?|стал[аи]?|утвержден[аы]?|утверждён[аы]?)\b",
                                  title, re.I)):
            return False
        return True
    # Роль, упомянутая ТОЛЬКО в биографии в лиде, не определяет, на какой
    # пост назначили сейчас. Требуем новое назначение непосредственно в лиде.
    if not REGIONAL_DEPUTY_GOV.search(lead):
        return False
    if re.search(r"\b(?:ранее|прежде|бывш\w*|до этого)\b.{0,95}?"
                 r"(?:вице[- ]?губернатор|заместител\w*\s+губернатор)", lead, re.I):
        return False
    return bool(re.search(r"\b(?:назначен[аоы]?|назначили|стал[аи]?|"
                          r"утвержден[аы]?|утверждён[аы]?)\b", lead, re.I))


def _deputy_full_names(text):
    """Пары (первые три буквы имени, основа фамилии), исключая отчество.

    Стандартный name_pairs не умеет надёжно разбирать «Оксана Игоревна
    Иванова»: он может принять отчество за фамилию. Не используем также
    лицо, которое НАЗНАЧАЕТ (губернатора, президента).
    """
    text = normalize(text)
    names = set()
    triples = []
    for m in _DEPUTY_PERSON_TRIPLE.finditer(text):
        first, middle, last = m.groups()
        if not _DEPUTY_PATRONYMIC.search(middle):
            continue
        if first.lower() in NAME_STOP or last.lower() in NAME_STOP:
            continue
        if name_stem(last) in APPOINTERS or name_stem(first) in APPOINTERS:
            continue
        names.add((first.lower().replace("ё", "е")[:3], name_stem(last)))
        triples.append(m.span())
    for m in re.finditer(r"\b([А-ЯЁ][а-яё-]{2,})\s+([А-ЯЁ][а-яё-]{3,})\b", text):
        first, last = m.groups()
        if any(start <= m.start() and m.end() <= stop for start, stop in triples):
            continue
        if (_DEPUTY_PATRONYMIC.search(first) or _DEPUTY_PATRONYMIC.search(last)
                or first.lower() in NAME_STOP or last.lower() in NAME_STOP):
            continue
        if name_stem(first) in APPOINTERS or name_stem(last) in APPOINTERS:
            continue
        names.add((first.lower().replace("ё", "е")[:3], name_stem(last)))
    return names


def regional_deputy_appointees(ev):
    """Надёжно определённое имя назначенного из заголовка или лида.

    Не используем сохранённое поле `person`: в старых карточках там может
    оказаться отчество, назначающий губернатор или герой комментария.
    """
    title = ev.get("title", "")
    if followup_appointment_commentary(title, ev.get("summary", "")):
        return set()
    headline = _deputy_full_names(title)
    if headline:
        return headline
    lead = first_sentence(ev.get("summary", ""), limit=320)
    found = _deputy_full_names(lead)
    return found if len(found) == 1 else set()


def regional_deputy_identity(ev):
    """Однозначный ключ назначения, не общий ключ «заместитель»."""
    if not is_regional_deputy_appointment(ev):
        return ""
    actors = regional_deputy_appointees(ev)
    if len(actors) != 1:
        return ""
    first, last = next(iter(actors))
    return f"deputy_appt:{ev.get('region', '')}:{first}:{last}"


def same_regional_deputy_appointment(a, b, days_apart):
    if days_apart > 3 or a.get("region") != b.get("region"):
        return False
    if not (is_regional_deputy_appointment(a) and is_regional_deputy_appointment(b)):
        return False
    pa, pb = regional_deputy_appointees(a), regional_deputy_appointees(b)
    # Должность не уникальна: без подтверждения одного и того же человека
    # автоматически объединять новости нельзя.
    return bool(pa and pb and pa & pb)


APPOINTMENT_ROLE_CLASSES = (
    ("minister", re.compile(r"\b(?:министр\w*|глав\w*\s+минздрава)\b", re.I)),
    ("director", re.compile(r"\b(?:гендиректор\w*|директор\w*|генеральн\w*\s+директор\w*)\b", re.I)),
    ("rector", re.compile(r"\bректор\w*\b", re.I)),
    ("prosecutor", re.compile(r"\bпрокурор\w*\b", re.I)),
    ("governor", re.compile(r"\bгубернатор\w*\b", re.I)),
)
LAUNCH_OBJECT_CLASSES = (
    ("production_line", re.compile(r"\b(?:производственн\w*\s+лини[юияе]|лини[юияе]\s+(?:по\s+)?производств\w*)\b", re.I)),
    ("terminal", re.compile(r"\bтерминал\w*\b", re.I)),
    ("energy_block", re.compile(r"\bэнергоблок\w*\b", re.I)),
    ("ship", re.compile(r"\b(?:ледокол\w*|судн\w*|фрегат\w*|корвет\w*|корабл\w*)\b", re.I)),
    ("workshop", re.compile(r"\bцех\w*\b", re.I)),
    ("factory", re.compile(r"\bзавод\w*\b", re.I)),
    ("hospital", re.compile(r"\b(?:больниц\w*|онкоцентр\w*|медцентр\w*)\b", re.I)),
    ("bridge", re.compile(r"\b(?:мост\w*|развязк\w*)\b", re.I)),
)


def appointment_role(ev):
    """Return a definite distinct class only when exactly one target role exists."""
    if ev.get("type") != "appointment":
        return ""
    title = ev.get("title", "")
    found = {key for key, rx in APPOINTMENT_ROLE_CLASSES if rx.search(title)}
    return next(iter(found)) if len(found) == 1 else ""


def launch_object(ev):
    """Look for the launched object next to the opening verb, not the operator."""
    if ev.get("type") != "launch":
        return ""
    title = ev.get("title", "")
    action = LAUNCH.search(title)
    # Usually 'company launched [object]'; if absent try the entire headline.
    after = title[action.end():] if action else title
    for kind, rx in LAUNCH_OBJECT_CLASSES:
        match = rx.search(after)
        if match:
            # Two numbered units of the same kind are distinct projects.
            number = re.match(r"\s*(?:№\s*|номер\s+)(\d+)\b", after[match.end():], re.I)
            return f"{kind}:no{number.group(1)}" if number else kind
    for kind, rx in LAUNCH_OBJECT_CLASSES:
        if kind != "factory" and rx.search(title):
            return kind
    return ""


def similar(a, b):
    """Дедупликация с учётом сущности и стадии, а не идентичности заголовков."""
    if honorary_citizen_key(a) or honorary_citizen_key(b):
        return same_honor(a, b)
    if governor_stage(a) or governor_stage(b):
        return same_governor_event(a, b)
    if a["type"] == "proceeding" or b["type"] == "proceeding":
        return same_proceeding(a, b)
    family = {"appointment", "leave"}
    if a["region"] != b["region"] or (a["type"] != b["type"] and not {a["type"], b["type"]} <= family):
        return False
    try:
        days_apart = abs((date.fromisoformat(a["date"]) - date.fromisoformat(b["date"])).days)
    except (KeyError, ValueError, TypeError):
        return False
    # Different confirmed offices and different physical objects are never
    # duplicates, even if the person/company and date match.
    if a["type"] == b["type"] == "appointment":
        ra, rb = appointment_role(a), appointment_role(b)
        if ra and rb and ra != rb:
            return False
    if a["type"] == b["type"] == "launch":
        oa, ob = launch_object(a), launch_object(b)
        if oa and ob:
            if oa.split(":", 1)[0] != ob.split(":", 1)[0]:
                return False
            if ":no" in oa and ":no" in ob and oa != ob:
                return False
    if a["type"] == b["type"] == "anniversary" and days_apart <= 14:
        return same_organization_anniversary(a, b)
    # Уникальная должность главы региона: разные заголовки и пропущенное
    # имя назначенного не должны создавать много Telegram-уведомлений.
    # При этом арест, увольнение и назначение — разные стадии.
    if regional_governor_stage(a) or regional_governor_stage(b):
        return same_regional_governor_decision(a, b, days_apart)
    # «вице-губернатор» = «заместитель губернатора», но только когда
    # установлен один и тот же человек (несколько заместителей — разные посты).
    deputy_a = is_regional_deputy_appointment(a)
    deputy_b = is_regional_deputy_appointment(b)
    if deputy_a or deputy_b:
        # Смена должности того же человека (например, директор → заместитель
        # губернатора) — самостоятельное кадровое событие. Не отдаём его в
        # общий fuzzy-match, который склеивает по одному ФИО.
        return bool(deputy_a and deputy_b
                    and same_regional_deputy_appointment(a, b, days_apart))
    if a["type"] == b["type"] == "appointment" and days_apart <= 10:
        if same_unique_regional_force_office(a, b):
            return True
    if days_apart > 3:
        return False
    if name_pairs(a["title"]) & name_pairs(b["title"]):      # одно «Имя Фамилия» (в любом падеже) в обоих заголовках
        return True
    pa, pb = position_key(a).split(":")[-1].split(), position_key(b).split(":")[-1].split()
    if len(pa) >= 2 and len(pb) >= 2 and (pa[:len(pb)] == pb or pb[:len(pa)] == pa):
        return True
    for x, y in ((a, b), (b, a)):
        spec = title_stems(x["title"]) - GENERIC_STEMS
        if len(spec) >= 2 and y.get("summary") and spec <= title_stems(y["title"] + " " + y["summary"][:500]):
            return True
    if a["type"] != b["type"]:
        return False
    sa, sb = title_stems(a["title"]) - GENERIC_STEMS, title_stems(b["title"]) - GENERIC_STEMS
    if len(sa) < 2 or len(sb) < 2:
        return False
    common = len(sa & sb)
    return common >= 2 and common / min(len(sa), len(sb)) >= 0.6

POSITION_KEY_DAYS = 10       # «тот же пост» блокирует повтор лишь 10 дней: позже на пост могут назначить другого


def blocked_by_seen(keys, seen, today):
    """Ключ персоны держится KEEP_SEEN_DAYS, ключ должности — только POSITION_KEY_DAYS."""
    for k in keys:
        if k not in seen:
            continue
        if k.startswith("honorary_citizen:"):
            try:
                if abs((today - date.fromisoformat(seen[k])).days) <= HONOR_REPEAT_DAYS:
                    return True
            except (ValueError, TypeError):
                return True
            continue
        if k.startswith("govdecision:"):
            # A later, genuinely new appointment of the same person is possible.
            window = 10 if ":governor_departure:" in k else 3
            try:
                if abs((today - date.fromisoformat(seen[k])).days) <= window:
                    return True
            except (ValueError, TypeError):
                return True
            continue
        if not k.startswith("pos:"):
            return True
        try:
            if abs((today - date.fromisoformat(seen[k])).days) <= POSITION_KEY_DAYS:
                return True
        except ValueError:
            return True
    return False


def event_keys(ev):
    honor_id = honorary_citizen_key(ev)
    if honor_id:
        return [honor_id]
    governor_id = governor_key(ev)
    if governor_id:
        # Do not append the generic position key, which can merge two governors.
        return [governor_id]
    deputy = regional_deputy_identity(ev)
    if deputy:
        # Имеющие подтверждённое имя региональные заместители не должны
        # блокировать друг друга по общему ключу должности или одной фамилии.
        return [deputy]
    keys = [event_key(ev)]
    if is_regional_deputy_appointment(ev):
        # Без имени нельзя создавать общий `pos:`, блокирующий другие
        # независимые назначения в правительстве того же региона.
        return keys
    # Каждая стадия процессуального дела самостоятельна; ключ должности
    # не должен блокировать арест после задержания или предъявление обвинения.
    if ev["type"] in ("workforce", "proceeding", "launch"):
        return keys
    pk = position_key(ev)
    if pk:
        keys.append(pk)
    return keys


def event_key(ev):
    honor_id = honorary_citizen_key(ev)
    if honor_id:
        return honor_id
    governor_id = governor_key(ev)
    if governor_id:
        return governor_id
    if ev["type"] == "proceeding":
        # Повтор одной стадии по нескольким источникам объединяем; новые
        # процессуальные решения по тому же лицу не склеиваем.
        who = proceeding_subject(ev)
        if not who:
            # Только губернатор — должность уникальна в конкретном регионе.
            # Не склеивать разных вице-губернаторов и министров без фамилий.
            who = proceeding_office(ev) or re.sub(r"[^а-яёa-z0-9]", "", ev["title"].lower())[:65]
        return f"proceeding:{ev['region']}:{who}:{ev.get('procedure_stage', 'unknown')}"
    # Одно решение по квоте/численности может перепечатываться с разными заголовками.
    if ev["type"] == "workforce":
        return workforce_fingerprint(ev)
    person = ev.get("person", "")
    if ev["type"] == "launch":
        # Avoid a company+month key which suppresses two separate facilities.
        org = (ev.get("orgs") or [""])[0].lower()
        obj = launch_object(ev)
        if not obj:
            obj = re.sub(r"[^а-яёa-z0-9 ]", "", ev.get("title", "").casefold())[:75]
        return f"launch:{ev['region']}:{org}:{obj}:{ev.get('date', '')}"
    if ev["type"] in ("visit", "anniversary", "award", "status", "ownership") and ev.get("orgs"):
        return f"{ev['type']}:{ev['region']}:{ev['orgs'][0].lower()}:{ev['date'][:7]}"
    if person:
        office = appointment_role(ev)
        if office:
            return f"{ev['type']}:{ev['region']}:{surname(person)}:{office}"
        return f"{ev['type']}:{ev['region']}:{surname(person)}"
    norm = re.sub(r"[^а-яёa-z0-9 ]", "", ev["title"].lower())
    return f"{ev['type']}:{norm[:70]}"


APPOINTER_FORM = re.compile(r"\b(?:назначил[аи]?|представил[аи]?|сформировал[аи]?|перераспредел\w+|утвердил[аи]?|"
                            r"освободил[аи]?|отправил[аи]?\s+в\s+отставку|сменил[аи]?)\b", re.I)


def priority(ev):
    """Порядок выбора записи среди дублей: авторитет источника; затем заголовок о назначенном
    («Фаламеева назначена министром») раньше заголовка о назначившем («Филимонов назначил министра»);
    затем заголовок с фамилией; затем дата."""
    title = ev.get("title", "")
    named_honor = ev.get("type") in ("title", "award") and _HONOR.search(title) and _recipient(title)
    return (ev.get("rank", 3), 1 if APPOINTER_FORM.search(title) else 0,
            0 if (ev.get("person") or named_honor) else 1, ev.get("date", ""))


def reconcile(events, cfg):
    """Перепроверить сохранённые события по текущим правилам: убрать то, что детектор
    больше не считает событием, и склеить дубли, оставив самый авторитетный источник.
    Вызывается при каждом прогоне и при --rebuild, чтобы правки правил применялись
    и к уже найденному. Возвращает (events, seen_keys)."""
    organizations = cfg.get("organizations", {})
    ranks = {src["id"]: src.get("rank", 3) for src in cfg.get("sources", [])}
    srcs = {src["id"]: src for src in cfg.get("sources", [])}
    kept, seen = [], {}
    for ev in events:
        ev["title"] = RUBRICS.sub("", DATE_WORDS.sub("", ev["title"])).strip()
        if srcs.get(ev.get("source_id"), {}).get("type") == "telegram" and ev.get("summary", "").startswith(ev["title"][:40]):
            ev["title"] = telegram_post_title(ev["summary"])   # сохранить переносы заголовка, не склеивать с лидом
        if len(ev["title"]) > 260:                       # только очевидно слипшийся заголовок с аннотацией
            ev["title"], tail = split_anchor(html_module.escape(ev["title"]))
            ev["title"] = html_module.unescape(ev["title"])
            if tail and not ev.get("summary"):
                ev["summary"] = html_module.unescape(tail)
        ev["rank"] = ranks.get(ev.get("source_id"), ev.get("rank", 3))
        ev["person"] = ev.get("person") or extract_person(ev["title"])
    for ev in sorted(events, key=priority):
        if promotional_material_reason(ev.get("link", ""), ev.get("title", ""), ev.get("summary", "")):
            continue
        det = detect_all(ev["title"], ev.get("summary", ""), organizations)
        if not det:
            continue
        relevance_source = srcs.get(ev.get("source_id"), {"region": ev.get("region")})
        relevant, _reason = event_relevance(
            ev["title"], ev.get("summary", ""), det, relevance_source, organizations)
        if not relevant:
            continue
        ev["type"], ev["level"], ev["org_class"] = det["type"], det["level"], det["org_class"]
        if det["type"] == "proceeding":
            ev["procedure_stage"] = det["stage"]
        else:
            ev.pop("procedure_stage", None)
        ev["person"] = detected_person(det, ev["title"], ev.get("summary", ""))
        src = srcs.get(ev.get("source_id"), {"region": ev.get("region")})
        region = event_region(src, ev["title"], ev.get("summary", ""), det)
        if not region:
            continue
        ev["region"] = region
        keys = event_keys(ev)
        if blocked_by_seen(keys, seen, date.fromisoformat(ev["date"])) or any(similar(ev, e) for e in kept):
            continue
        for k in keys:
            seen[k] = ev["date"]
        kept.append(ev)
    return kept, seen


def run(today=None, verbose=True):
    cfg = ensure_university_source(load_json(SOURCES_FILE, {"sources": [], "organizations": {}}))
    organizations = cfg.get("organizations", {})
    feeds_cache = load_json(FEEDS_CACHE, {})
    today = today or g.msk_today()
    # Одноразовая проверенная публикация за 23.11.2026. Работает только
    # в эту дату, без запросов к сайту; дальше обычная лента Росбалта.
    if today.isoformat() == "2026-11-23":
        featured = load_json(Path("data/news/featured_staffing_2026-11-23.json"), [])
        if featured:
            cfg["sources"].append({
                "id": "rosbalt_featured_20261123", "name": "Росбалт",
                "type": "curated", "region": None, "rank": 2,
                "items": featured,
            })
    events, seen_from_events = reconcile(load_json(EVENTS_FILE, []), cfg)
    seen = load_json(SEEN_FILE, {})
    seen.update(seen_from_events)
    fresh_from = today - timedelta(days=FRESH_DAYS)

    candidates, statuses = [], []
    trace_for_candidate = {}
    diagnostics = {"items_received": 0, "items_fresh": 0, "detected": 0, "relevance_accepted": 0, "relevance_rejected": 0, "region_rejected": 0, "candidates": 0, "rejection_reasons": {}, "rejected_examples": [], "not_detected": 0, "duplicates": 0}
    trace = Trace(today.isoformat())
    for src in cfg["sources"]:
        if not src.get("enabled", True):
            continue
        t0 = time.time()
        # Совместимость с исходным контрактом fetch_source(src, feeds_cache).
        # Тесты и внешние интеграции могут подменять эту функцию двухаргументным mock.
        items, status = fetch_source(src, feeds_cache)
        trace.source(src["id"], status, len(items))
        statuses.append((src["id"], src["name"], status, round(time.time() - t0, 1)))
        if verbose:
            print(f"  {src['id']:<16} {status:<40} {time.time() - t0:4.1f}s", flush=True)
        for it in items:
            trace_index = trace.start_item(it.get("link"), src["id"], it.get("title", ""))
            diagnostics["items_received"] += 1
            d = parse_date(it.get("date"))
            if d and d < fresh_from:
                trace.update(trace_index, "old", "outside_freshness_window")
                continue
            diagnostics["items_fresh"] += 1
            promo_reason = promotional_material_reason(it.get("link", ""), it.get("title", ""), it.get("summary", ""))
            if promo_reason:
                trace.update(trace_index, "relevance_rejected", promo_reason)
                diagnostics["relevance_rejected"] += 1
                diagnostics["rejection_reasons"][promo_reason] = diagnostics["rejection_reasons"].get(promo_reason, 0) + 1
                continue
            det = detect_all(it["title"], it.get("summary", ""), organizations)
            if not det:
                diagnostics["not_detected"] += 1
                trace.update(trace_index, "not_detected", "event_not_recognized")
                continue
            diagnostics["detected"] += 1
            relevant, reason = event_relevance(
                it["title"], it.get("summary", ""), det, src, organizations)
            if not relevant:
                trace.update(trace_index, "relevance_rejected", reason)
                diagnostics["relevance_rejected"] += 1
                diagnostics["rejection_reasons"][reason] = diagnostics["rejection_reasons"].get(reason, 0) + 1
                if len(diagnostics["rejected_examples"]) < 15:
                    diagnostics["rejected_examples"].append({"reason": reason, "title": it["title"][:180], "source": src.get("name", "")})
                if verbose:
                    print(f"    [REJECT:{reason}] {it['title'][:110]}")
                continue
            diagnostics["relevance_accepted"] += 1
            text = f"{it['title']} {it.get('summary', '')}"
            region = event_region(src, it["title"], it.get("summary", ""), det)
            if not region:
                trace.update(trace_index, "region_rejected", "region_not_confirmed")
                diagnostics["region_rejected"] += 1
                continue
            ev = {"type": det["type"], "level": det["level"], "org_class": det["org_class"],
                  "region": region, "title": normalize(it["title"]).strip(), "summary": normalize(it.get("summary", ""))[:400],
                  "link": it.get("link", ""), "date": (d or today).isoformat(),
                  "source": src["name"], "source_id": src["id"], "rank": src.get("rank", 3),
                  "person": detected_person(det, it["title"], it.get("summary", "")),
                  "orgs": sorted({o[1] for o in det["orgs"]})}
            if det["type"] == "proceeding":
                ev["procedure_stage"] = det["stage"]
            candidates.append(ev)
            trace_for_candidate[id(ev)] = trace_index
            trace.update(trace_index, "candidate")
            diagnostics["candidates"] += 1

    # одно событие — одна запись: сначала самый авторитетный источник, остальные склеиваются
    candidates.sort(key=priority)
    new_events = []
    # Старое решение об отставке губернатора может получить новые заголовки
    # спустя несколько дней. Проверяем его в сохранённой базе до 10 дней;
    # остальные события остаются на прежнем коротком окне.
    recent_cut = (today - timedelta(days=4)).isoformat()
    departure_cut = (today - timedelta(days=10)).isoformat()
    proceeding_cut = (today - timedelta(days=7)).isoformat()
    honor_cut = (today - timedelta(days=HONOR_REPEAT_DAYS)).isoformat()
    recent = [e for e in events if e.get("date", "") >= recent_cut or (
        e.get("date", "") >= departure_cut
        and (regional_governor_stage(e) == "governor_departure"
             or governor_stage(e) == "governor_departure")
    ) or (
        e.get("date", "") >= proceeding_cut and e.get("type") == "proceeding"
    ) or (
        e.get("date", "") >= honor_cut and honorary_citizen_key(e)
    )]
    for ev in candidates:
        keys = event_keys(ev)
        match = next((e for e in recent + new_events if similar(ev, e) or set(keys) & set(event_keys(e))), None)
        if match is not None:
            diagnostics["duplicates"] += 1
            trace.update(trace_for_candidate[id(ev)], "duplicate", "same_event_existing_or_in_run")
            # то же событие уже есть; если новый источник авторитетнее — заменяем запись, не уведомляя повторно
            if priority(ev) < priority(match) and match not in new_events:
                ev["upgraded"] = True
                ev["date"] = min(ev["date"], match["date"])
                events.remove(match)
                recent.remove(match)
                new_events.append(ev)
                trace.update(trace_for_candidate[id(ev)], "upgraded", "better_source")
            elif priority(ev) < priority(match):
                trace.update(trace_for_candidate[id(match)], "duplicate", "superseded_by_better_source")
                new_events[new_events.index(match)] = ev
                trace.update(trace_for_candidate[id(ev)], "upgraded", "better_source")
            for k in keys:
                seen[k] = today.isoformat()
            continue
        if blocked_by_seen(keys, seen, today):
            diagnostics["duplicates"] += 1
            trace.update(trace_for_candidate[id(ev)], "duplicate", "seen_key")
            continue
        for k in keys:
            seen[k] = today.isoformat()
        new_events.append(ev)
        trace.update(trace_for_candidate[id(ev)], "new")
    fresh_new = [e for e in new_events if not e.pop("upgraded", False)]

    # ── сохранить ──
    cutoff = (today - timedelta(days=KEEP_EVENTS_DAYS)).isoformat()
    events = [e for e in events if e.get("date", "") >= cutoff] + new_events
    events.sort(key=lambda e: (e["date"], e["region"], e["title"]), reverse=True)
    seen_cut = (today - timedelta(days=KEEP_SEEN_DAYS)).isoformat()
    seen = {k: v for k, v in seen.items() if v >= seen_cut}
    save_json(EVENTS_FILE, events)
    save_json(SEEN_FILE, seen)
    save_json(FEEDS_CACHE, feeds_cache)
    trace.write()
    errors = [s for s in statuses if s[2].startswith("error")]
    diagnostics["new_events"] = len(fresh_new)
    diagnostics["sources"] = trace.sources
    diagnostics["trace_file"] = str(TRACE_FILE)
    save_json(RUN_SUMMARY, {"date": today.isoformat(), "new": fresh_new, "diagnostics": diagnostics,
                            "sources_total": len(statuses), "sources_failed": len(errors),
                            "failed": [{"id": s[0], "name": s[1], "status": s[2]} for s in errors]})
    render_page(events, today)
    if verbose:
        print(f"\nИсточников: {len(statuses)}, с ошибкой: {len(errors)}; новых событий: {len(fresh_new)}")
        print("Фильтр: получено {items_received}, свежих {items_fresh}, детектор {detected}, "
              "принято {relevance_accepted}, отклонено {relevance_rejected}, "
              "без региона {region_rejected}, кандидатов {candidates}".format(**diagnostics))
        print("Причины отклонения:", diagnostics["rejection_reasons"])
        for ev in fresh_new:
            print(f"  [{ev['type']}/{ev['level']}] {ev['region']}: {ev['title'][:100]}")
    return fresh_new, statuses



def audit_url(url, title_override=None, summary_override=""):
    """Только диагностика. Не меняет события, не запускает рассылку."""
    from urllib.parse import urlsplit
    result = {"url": url, "trace": trace_lookup(url), "published": False}
    key = canonical_url(url)
    if not key:
        result["error"] = "URL должен быть http/https"
        print(json.dumps(result, ensure_ascii=False, indent=2))
        return 2
    events = load_json(EVENTS_FILE, [])
    result["published"] = any(canonical_url(e.get("link")) == key for e in events)
    cfg = ensure_university_source(load_json(SOURCES_FILE, {"sources": [], "organizations": {}}))
    host = urlsplit(url).hostname or ""
    matched = None
    for src in cfg.get("sources", []):
        source_url = src.get("url", "") or src.get("news_url", "")
        if src.get("type") == "telegram":
            source_url = "https://t.me/" + source_url
        try:
            shost = urlsplit(source_url).hostname or ""
        except ValueError:
            shost = ""
        if shost and (host == shost or host == "www." + shost or shost == "www." + host):
            matched = src
            break
    result["source_registered"] = bool(matched)
    result["source_id"] = (matched or {}).get("id")
    if TRACE_FILE.exists():
        trace_data = load_json(TRACE_FILE, {})
        result["source_last_run"] = next((entry for entry in trace_data.get("sources", [])
            if entry.get("id") == result["source_id"]), None)
    if result["trace"].get("found"):
        result["interpretation"] = "Решение записано при последнем прогоне; классификатор повторно не запускается"
        print(json.dumps(result, ensure_ascii=False, indent=2))
        return 0
    result["interpretation"] = "URL не найден в последнем прогоне. Проверяем возможность классификации отдельно; это НЕ гарантия попадания в ленту"
    try:
        item = ({"title": title_override, "summary": summary_override, "link": url}
                if title_override else article_metadata(http_get(url), url))
        if not item:
            result["analysis"] = {"status": "unreadable", "reason": "article_title_unavailable"}
        else:
            title, summary = item["title"], item.get("summary", "")
            promo_reason = promotional_material_reason(url, title, summary)
            det = None if promo_reason else detect_all(title, summary, cfg.get("organizations", {}))
            if promo_reason:
                result["analysis"] = {"status": "rejected", "reason": promo_reason, "title": title}
            elif not det:
                result["analysis"] = {"status": "not_detected", "title": title}
            else:
                src = matched or {"id": "audit_only", "region": None}
                ok, reason = event_relevance(title, summary, det, src, cfg.get("organizations", {}))
                region = event_region(src, title, summary, det) if ok else None
                duplicate = False
                if ok and region:
                    probe = {"title": title, "summary": summary, "link": url,
                             "date": str(item.get("date", ""))[:10] or date.today().isoformat(),
                             "type": det["type"], "level": det["level"],
                             "org_class": det["org_class"], "region": region,
                             "orgs": sorted({o[1] for o in det.get("orgs", [])}),
                             "person": detected_person(det, title, summary)}
                    if det["type"] == "proceeding":
                        probe["procedure_stage"] = det["stage"]
                    probe_keys = set(event_keys(probe))
                    duplicate = any(similar(probe, e) or bool(probe_keys & set(event_keys(e)))
                                    for e in events)
                result["analysis"] = {"title": title, "event_type": det["type"], "relevant": ok,
                                      "reason": reason, "region": region,
                                      "duplicate_existing": duplicate,
                                      "status": ("already_in_events" if duplicate else "eligible")
                                                if ok and region else "rejected"}
    except requests.RequestException as exc:
        result["analysis"] = {"status": "fetch_failed", "reason": type(exc).__name__}
    except Exception as exc:
        result["analysis"] = {"status": "error", "reason": type(exc).__name__}
    print(json.dumps(result, ensure_ascii=False, indent=2))
    return 0

