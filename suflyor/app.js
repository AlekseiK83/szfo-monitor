async function llmText(prompt, signal){
  const st = App.settings; let r;
  try{
    if(st.provider==='anthropic'){
      if(!st.aKey) throw {code:'no_key'};
      r = await fetch('https://api.anthropic.com/v1/messages', {method:'POST', signal, headers:{'content-type':'application/json','x-api-key':st.aKey,'anthropic-version':'2023-06-01','anthropic-dangerous-direct-browser-access':'true'}, body:JSON.stringify({model:st.aModel, max_tokens:16000, messages:[{role:'user', content:prompt}]})});
    } else if(st.provider==='openai'){
      if(!st.oBase || !st.oModel) throw {code:'no_key'};
      const h={'content-type':'application/json'}; if(st.oKey) h.authorization='Bearer '+st.oKey;
      r = await fetch(st.oBase.replace(/\/+$/,'')+'/chat/completions', {method:'POST', signal, headers:h, body:JSON.stringify({model:st.oModel, temperature:0.2, messages:[{role:'user', content:prompt}]})});
    } else throw {code:'no_key'};
  }catch(e){ if(e && e.code) throw e; if(e && e.name==='AbortError') throw {code:'cancelled'}; throw {code:'network', message:String(e && e.message || e)}; }
  if(!r.ok){
    let body=''; try{ body = await r.text(); }catch(_){}
    const code = r.status===401||r.status===403 ? 'auth' : r.status===429 ? 'rate_limited' : r.status===529||r.status===503 ? 'overloaded' : r.status===413 || /too long|context/i.test(body) ? 'too_large' : 'http';
    throw {code, message:'HTTP '+r.status+': '+body.slice(0,300)};
  }
  const d = await r.json();
  if(st.provider==='anthropic') return (d.content||[]).filter(c=>c.type==='text').map(c=>c.text).join('');
  return d.choices && d.choices[0] && d.choices[0].message ? d.choices[0].message.content||'' : '';
}
