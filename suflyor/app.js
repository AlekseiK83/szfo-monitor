function countSeq(toks, seq){
  let c=0;
  for(let i=0;i<=toks.length-seq.length;i++){
    let ok=true; for(let j=0;j<seq.length;j++){ if(toks[i+j]!==seq[j]){ok=false;break;} }
    if(ok) c++;
  }
  return c;
}

function computeMetrics(parsed){
  const text = parsed.text;
  const toks = tokens(text);
  const words = toks.length;
  const m = {words, duration:parsed.duration, wpm:null, fillers:[], fillerTotal:0, fillersPer100:0, you:0, we:0, kanc:0, kancList:[], numbers:0, questions:(text.match(/\?/g)||[]).length, avgSentence:null, paceSeries:null, hesitations:0};
  if(parsed.duration && parsed.duration>20) m.wpm = Math.round(words/(parsed.duration/60));
  for(const f of FILLERS){ const c = countSeq(toks,f); if(c){ m.fillers.push({w:f.join(' '),c}); m.fillerTotal+=c; } }
  m.hesitations = toks.filter(t=>/^(э+|м+|ээ+м*|хм+)$/.test(t)).length;
  if(m.hesitations){ m.fillers.push({w:'э-э / м-м',c:m.hesitations}); m.fillerTotal+=m.hesitations; }
  m.fillers.sort((a,b)=>b.c-a.c);
  m.fillersPer100 = words ? +(m.fillerTotal/words*100).toFixed(1) : 0;
  for(const t of toks){ if(YOU.has(t)) m.you++; else if(WE.has(t)) m.we++; if(/\d/.test(t)) m.numbers++; }
  const kc = {};
  for(const p of KANC_PHRASES){ const c=countSeq(toks,p); if(c){ kc[p.join(' ')]=(kc[p.join(' ')]||0)+c; } }
  for(const t of toks){ const r = KANC_ROOTS.find(r=>t.startsWith(r)); if(r){ kc[t]=(kc[t]||0)+1; } }
  m.kancList = Object.entries(kc).map(([w,c])=>({w,c})).sort((a,b)=>b.c-a.c);
  m.kanc = m.kancList.reduce((s,x)=>s+x.c,0);
  const ends = (text.match(/[.!?…]+/g)||[]).length;
  if(ends >= Math.max(3, words/40)) m.avgSentence = Math.round(words/ends);
  if(parsed.timed && parsed.duration){
    const mins = Math.max(1, Math.ceil(parsed.duration/60));
    const arr = new Array(mins).fill(0);
    for(const ln of parsed.lines){ if(ln.t==null) continue; const i=Math.min(mins-1, Math.floor(ln.t/60)); arr[i]+=tokens(ln.text).length; }
    // последняя неполная минута — пересчитать в слова/мин
    const tail = parsed.duration - (mins-1)*60;
    if(tail>15 && tail<60) arr[mins-1] = Math.round(arr[mins-1]*60/tail);
    else if(tail<=15 && mins>1) arr.pop();
    m.paceSeries = arr;
  }
  return m;
}

function paceScore(wpm){
  if(wpm==null) return null;
  if(wpm>=110 && wpm<=150) return 10;
  const d = wpm<110 ? 110-wpm : wpm-150;
  return Math.max(1, Math.min(10, +(10 - d/8).toFixed(1)));
}

function accuracyScore(claims){
  const list = Array.isArray(claims)?claims:[];
  if(!list.length) return {score:4, note:'В выступлении почти нет конкретики по продукту.'};
  let s = 10; const cnt = {};
  for(const c of list){
    const st = c.status; cnt[st]=(cnt[st]||0)+1;
    if(st==='ошибка') s-=2.5; else if(st==='недопустимое обещание') s-=3; else if(st==='неточно') s-=1; else if(st==='нет в базе') s-=0.5;
  }
  if(list.length<3) s = Math.min(s, 8);
  s = Math.max(1, Math.min(10, +s.toFixed(1)));
  const parts = FACT_STATUSES.filter(k=>cnt[k]).map(k=>k+': '+cnt[k]);
  return {score:s, note:'Утверждений: '+list.length+(parts.length?' ('+parts.join(', ')+')':'')};
}

function quoteMatch(quote, tNorm, tToks){
  const parts = String(quote||'').split(/\.\.\.|…/).map(normText).filter(p=>p.length>0);
  if(!parts.length) return 1;
  let worst = 1;
  for(const p of parts){
    if((' '+tNorm+' ').includes(' '+p+' ')) continue;
    const pt = p.split(' ');
    if(pt.length<3){ worst = Math.min(worst, tNorm.includes(p)?1:0); continue; }
    const L = pt.length+2; let best = 0;
    for(let i=0;i<=Math.max(0,tToks.length-pt.length);i++){
      const win = tToks.slice(i, i+L); const bag = {};
      for(const w of win) bag[w]=(bag[w]||0)+1;
      let hit=0; for(const w of pt){ if(bag[w]){ hit++; bag[w]--; } }
      const r = hit/pt.length; if(r>best){ best=r; if(best===1) break; }
    }
    worst = Math.min(worst, best);
  }
  return worst;
}

function collectQuotes(f){
  const q = [];
  (f.structure?.blocks||[]).forEach((b,i)=>{ if(b.quote) q.push({ref:'structure.blocks['+i+'] '+(b.name||''), quote:b.quote}); });
  (f.facts?.claims||[]).forEach(c=>{ if(c.quote) q.push({ref:'facts.'+(c.id||'?'), quote:c.quote}); });
  (f.rubric?.criteria||[]).forEach(c=>{ if(c.evidence) q.push({ref:'rubric.'+c.key, quote:c.evidence}); });
  (f.rubric?.strengths||[]).forEach(s=>{ if(s.quote) q.push({ref:'rubric.strengths.'+(s.id||'?'), quote:s.quote}); });
  (f.rubric?.weaknesses||[]).forEach(s=>{ if(s.quote) q.push({ref:'rubric.weaknesses.'+(s.id||'?'), quote:s.quote}); });
  return q;
}

function quoteCheck(findings, text){
  const tNorm = normText(text), tToks = tNorm.split(' ');
  const qs = collectQuotes(findings);
  const bad = [];
  for(const q of qs){ const r = quoteMatch(q.quote, tNorm, tToks); q.match=r; if(r<0.8) bad.push(q); }
  return {total:qs.length, ok:qs.length-bad.length, bad, coverage: qs.length ? (qs.length-bad.length)/qs.length : 1};
}

function computeScores(findings, metrics){
  const byKey = {};
  for(const c of (findings.rubric?.criteria||[])) byKey[c.key]=c;
  const acc = accuracyScore(findings.facts?.claims);
  const pace = paceScore(metrics.wpm);
  const rows = CRITERIA.map(c=>{
    let score=null, comment='', evidence='';
    if(c.src==='facts'){ score=acc.score; comment=acc.note; }
    else if(c.src==='metrics'){ score=pace; comment = metrics.wpm==null ? 'Длительность неизвестна: критерий не учтён.' : metrics.wpm+' слов/мин при норме 110–150.'; }
    else { const r = byKey[c.key]; if(r && isFinite(+r.score)){ score=Math.max(1,Math.min(10,+r.score)); comment=r.comment||''; evidence=r.evidence||''; } }
    return {...c, score, comment, evidence};
  });
  const used = rows.filter(r=>r.score!=null);
  const wsum = used.reduce((s,r)=>s+r.w,0);
  const total = wsum ? Math.round(used.reduce((s,r)=>s+r.w*r.score,0)/wsum*10) : null;
  return {rows, total};
}
