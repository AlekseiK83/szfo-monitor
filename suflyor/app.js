async function runAuto(){
  if(App.running) return;
  const s = App.cur; const parsed = prepareInput();
  if(tokens(parsed.text).length < 60){ $('runNote').textContent='Слишком короткий текст: нужно хотя бы 60 слов.'; return; }
  const ctx = readCtx(); Object.assign(s, {manager:ctx.manager, audience:ctx.audience, format:ctx.format, goal:ctx.goal});
  const st = App.settings; const threshold = st.threshold, maxIter = st.maxIter;
  const key = hashStr(parsed.text+'|'+JSON.stringify(ctx)+'|'+st.provider+st.aModel+st.oModel+'|'+hashStr(App.kbZp+App.kbSp));
  if(!s.memo || s.memo.key!==key) s.memo = {key};
  const memo = s.memo;
  App.running=true; $('runBtn').disabled=true; $('stopBtn').classList.remove('hidden'); $('runNote').textContent=''; $('manualCard').classList.add('hidden');
  const t0=Date.now(); const timer=setInterval(()=>{ $('pipeTime').textContent=fmtTime((Date.now()-t0)/1000); },1000);
  resetSteps(); $('log').innerHTML=''; $('logBox').classList.add('hidden'); $('report').innerHTML='';
  let current='metrics';
  try{
    const metrics = computeMetrics(parsed); const text = parsed.text;
    setStep('metrics',{status:'done', conf:metrics.duration?99:90, note: metrics.duration ? `${metrics.words} слов, ${metrics.wpm} слов/мин, паразитов ${metrics.fillersPer100} на 100 слов` : `${metrics.words} слов; длительность неизвестна, темп не посчитан`});
    const job = async (id, builder)=>{
      if(memo[id]){ setStep(id,{status:'done', conf:clampPct(memo[id].confidence), note:'из предыдущего запуска'}); return memo[id]; }
      setStep(id,{status:'run'});
      try{ const r = await ask(builder(ctx, metrics, text)); memo[id]=r; saveSoon(); setStep(id,{status:'done', conf:clampPct(r.confidence), note:'самооценка модели до проверки'}); return r; }
      catch(e){ setStep(id,{status:'err'}); throw e; }
    };
    current='structure';
    const [structure, facts, rubric] = await Promise.all([job('structure',pStructure), job('facts',pFacts), job('rubric',pRubric)]);
    let findings = memo.verified || normFindings({structure, facts, rubric});
    let conf=0, iter=0, log=memo.log||[], qcConf=memo.qcConf, stepConf=memo.stepConf||{};
    if(memo.verified){ conf=memo.conf; iter=memo.iter; }
    else {
      for(iter=1; iter<=maxIter; iter++){
        current='quotes';
        const qc = quoteCheck(findings, text); qcConf = Math.round(qc.coverage*100);
        setStep('quotes',{status:'done', conf:qcConf, iter:`${iter}/${maxIter}`, note:`подтверждено ${qc.ok} из ${qc.total} цитат`});
        current='verify';
        setStep('verify',{status:'run', iter:`${iter}/${maxIter}`, note:'проверяющий перечитывает расшифровку и базы'});
        const ver = await ask(pVerify(ctx, metrics, text, findings, qc, iter));
        conf = clampPct(ver.overall); if(qc.coverage<0.95) conf=Math.min(conf, qcConf);
        const sc = ver.confidence||{}; stepConf={structure:clampPct(sc.structure), facts:clampPct(sc.facts), rubric:clampPct(sc.rubric)};
        setStep('structure',{conf:stepConf.structure, note:'после проверки'}); setStep('facts',{conf:stepConf.facts, note:'после проверки'}); setStep('rubric',{conf:stepConf.rubric, note:'после проверки'});
        const issues = Array.isArray(ver.issues)?ver.issues:[];
        log.push({iter, conf, issues, missed:Array.isArray(ver.missed_claims)?ver.missed_claims:[], badQuotes:qc.bad.map(b=>b.quote), verdict:ver.verdict||''});
        renderLog(log, threshold);
        if(conf>=threshold){ setStep('verify',{status:'done', conf, iter:`${iter}/${maxIter}`, note:`порог ${threshold}% достигнут`}); break; }
        if(iter===maxIter){ setStep('verify',{status:'done', conf, iter:`${iter}/${maxIter}`, note:`порог ${threshold}% не достигнут, лимит итераций исчерпан`}); break; }
        setStep('verify',{status:'run', conf, iter:`${iter}/${maxIter}`, note:`исправляю ${issues.length} замечани${plural(issues.length,'е','я','й')}`});
        const rev = await ask(pRevise(ctx, metrics, text, findings, ver, qc));
        findings = normFindings({structure:rev.structure||findings.structure, facts:rev.facts||findings.facts, rubric:rev.rubric||findings.rubric});
      }
      iter=Math.min(iter,maxIter);
      Object.assign(memo, {verified:findings, conf, iter, log, qcConf, stepConf}); saveSoon();
    }
    current='final';
    let fin = memo.final;
    if(!fin){ setStep('final',{status:'run'}); fin = await ask(pFinal(ctx, metrics, findings, computeScores(findings, metrics))); memo.final=fin; }
    setStep('final',{status:'done', note:'готово'});
    finishReport('auto', ctx, metrics, findings, fin, conf, iter, log, {qcConf, stepConf});
  } catch(e){
    if(stepState[current] && stepState[current].status==='run') setStep(current,{status:'err'});
    const code = e && e.code;
    $('runNote').textContent = (ERR[code] || 'Ошибка') + (code && ERR[code] ? '' : ': '+(e && (e.message||e.code) || e));
    if(code==='no_key') $('runNote').innerHTML = esc(ERR.no_key)+' <a href="#settings">Перейти</a>';
    saveSession();
  } finally {
    clearInterval(timer); App.running=false; $('runBtn').disabled=false; $('stopBtn').classList.add('hidden');
  }
}

