#!/usr/bin/env python3
"""Rename the news tile on the SZFO monitor home page, without altering either pipeline.

The HTML is generated by generate.py, so the text must be changed in BOTH
index.html (current publication) and generate.py (future publications).
If a target is ambiguous, fail without writing either file.
"""

from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

TARGETS = (Path('index.html'), Path('generate.py'))
NEW = 'Значимые события'
# Include the possible "Новости —" prefix so the resulting label stays concise.
OLD_LABEL = re.compile(
    r'(?:Новости\s*[-—–:]\s*)?Назначения\s+и\s+звания',
    flags=re.IGNORECASE,
)
NEWS_LINK = re.compile(r'news\.html', flags=re.IGNORECASE)
NEW_LABEL = re.compile(r'Значимые\s+события', flags=re.IGNORECASE)
NEWS_ANCHOR = re.compile(r'<a\b[^>]*news\.html[^>]*>.*?</a\s*>', flags=re.IGNORECASE | re.DOTALL)
MAX_NEAR_DISTANCE = 2200


class UnsafeChange(ValueError):
    pass


def _distance(i: int, positions: list[int]) -> int:
    return min(abs(i - p) for p in positions)


def rewrite(source: str, filename: str) -> tuple[str, int, str]:
    """Return (new source, changed phrases, reason). No file access or writes."""
    links = [m.start() for m in NEWS_LINK.finditer(source)]
    if not links:
        raise UnsafeChange(f'{filename}: не найден переход news.html; структура не подтверждена')

    old = list(OLD_LABEL.finditer(source))
    anchor_spans = [a.span() for a in NEWS_ANCHOR.finditer(source)]
    # For normal HTML, the visible text must be INSIDE the news link, not
    # in a nearby editorial paragraph that happens to mention appointments.
    inside_anchor = [m for m in old if any(a <= m.start() and m.end() <= b
                                         for a, b in anchor_spans)]
    already_inside_anchor = any(
        any(a <= m.start() and m.end() <= b for a, b in anchor_spans)
        for m in NEW_LABEL.finditer(source)
    )
    nearby = [m for m in old if _distance(m.start(), links) <= MAX_NEAR_DISTANCE]

    if inside_anchor:
        chosen = inside_anchor
    elif already_inside_anchor:
        return source, 0, 'виджет уже переименован'
    elif nearby:
        chosen = nearby
    elif len(old) == 1:
        # Some templates define the visible label in a string table far from URLs.
        chosen = old
    elif not old:
        already = [m for m in NEW_LABEL.finditer(source)
                   if _distance(m.start(), links) <= MAX_NEAR_DISTANCE]
        if already or (len(list(NEW_LABEL.finditer(source))) == 1):
            return source, 0, 'уже переименовано'
        raise UnsafeChange(f'{filename}: старое и новое название виджета не найдены')
    else:
        raise UnsafeChange(
            f'{filename}: найдено {len(old)} старых названий, но непонятно, '
            'какое относится к ссылке news.html. Правка отменена.'
        )

    result = source
    for match in reversed(chosen):
        result = result[:match.start()] + NEW + result[match.end():]

    if len(NEWS_LINK.findall(result)) != len(links):
        raise UnsafeChange(f'{filename}: обнаружено изменение ссылок news.html')
    if len(NEW_LABEL.findall(result)) < len(chosen):
        raise UnsafeChange(f'{filename}: новое название не появилось')
    return result, len(chosen), 'обновлено'


def run(root: Path, dry_run: bool) -> dict[str, int]:
    planned: list[tuple[Path, str, str, int, str]] = []
    # Plan BOTH modifications and validate before writing anything.
    for relative_path in TARGETS:
        path = root / relative_path
        if not path.is_file():
            raise UnsafeChange(f'Отсутствует {relative_path}; никаких изменений не внесено')
        original = path.read_bytes().decode('utf-8')
        replacement, count, message = rewrite(original, str(relative_path))
        planned.append((path, original, replacement, count, message))

    counts = {}
    for path, original, replacement, count, message in planned:
        counts[path.name] = count
        print(f'{path.name}: {message}; замен: {count}')
        if not dry_run and original != replacement:
            path.write_bytes(replacement.encode('utf-8'))

    if dry_run:
        print('Предварительная проверка: файлы НЕ изменены')
    else:
        print('Проверено: ссылка news.html и весь остальной код сохранены')
    return counts


def self_test() -> None:
    from tempfile import TemporaryDirectory

    cases = [
        ('<a href="news.html">Назначения и звания</a>',
         '<a href="news.html">Значимые события</a>'),
        ('<a href="news.html"><h3>Новости — назначения и звания</h3></a>',
         '<a href="news.html"><h3>Значимые события</h3></a>'),
        ("const tile = {title:'Назначения и звания',href:'news.html'};",
         "const tile = {title:'Значимые события',href:'news.html'};"),
        ('<a href="news.html">Значимые события</a>',
         '<a href="news.html">Значимые события</a>'),
        ('<nav><a href="news.html">Назначения и звания</a></nav>'
         '<section><a href="./news.html">Назначения и звания</a></section>',
         '<nav><a href="news.html">Значимые события</a></nav>'
         '<section><a href="./news.html">Значимые события</a></section>'),
        ('<a href="news.html">Значимые события</a>'
         '<p>Назначения и звания — прежнее описание</p>',
         '<a href="news.html">Значимые события</a>'
         '<p>Назначения и звания — прежнее описание</p>'),
        ('<a href="news.html">Назначения и звания</a>\n'
         '<p>Назначения и звания министерств — отдельная категория</p>' + ' ' * 3000,
         '<a href="news.html">Значимые события</a>\n'
         '<p>Назначения и звания министерств — отдельная категория</p>' + ' ' * 3000),
    ]
    for index, (before, expected) in enumerate(cases, 1):
        result, _, _ = rewrite(before, f'case {index}')
        assert result == expected, f'case {index}: unexpected output'
        same, n, _ = rewrite(result, f'idempotent {index}')
        # An explanation may still contain the old words (case 5), but no
        # edit should take place on the already-renamed, nearby widget.
        assert same == expected and n == 0, f'case {index}: second run changed code'

    with TemporaryDirectory() as d:
        root = Path(d)
        (root / 'index.html').write_text('<a href="news.html">Назначения и звания</a>', encoding='utf-8')
        # A missing generator must abort BEFORE index.html changes.
        try:
            run(root, dry_run=False)
        except UnsafeChange:
            pass
        else:
            raise AssertionError('Missing generator should stop')
        assert 'Назначения и звания' in (root / 'index.html').read_text(encoding='utf-8')
        (root / 'generate.py').write_text('TEMPLATE = "<a href=\\\"news.html\\\">Назначения и звания</a>"', encoding='utf-8')
        assert run(root, dry_run=True) == {'index.html': 1, 'generate.py': 1}
        assert 'Назначения и звания' in (root / 'index.html').read_text(encoding='utf-8')
        assert run(root, dry_run=False) == {'index.html': 1, 'generate.py': 1}
        assert run(root, dry_run=False) == {'index.html': 0, 'generate.py': 0}

    print('SELF-TEST: PASS (7 markup variants, idempotency, safety, dry-run)')


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--self-test', action='store_true')
    parser.add_argument('--dry-run', action='store_true')
    parser.add_argument('--root', type=Path, default=Path('.'))
    args = parser.parse_args()
    try:
        if args.self_test:
            self_test()
        else:
            run(args.root, args.dry_run)
    except (UnsafeChange, UnicodeError) as exc:
        print(f'БЕЗОПАСНАЯ ОСТАНОВКА: {exc}', file=sys.stderr)
        return 1
    return 0


if __name__ == '__main__':
    raise SystemExit(main())
