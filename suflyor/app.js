function scoreChart(done){
  if(!done.length) return '';
  const W=520,H=170,pl=30,pr=10,pt=12,pb=24;
  const n=done.length, x=i=> n===1 ? (pl+(W-pr))/2 : pl+(W-pl-pr)*(i/(n-1)), y=v=>pt+(H-pt-pb)*(1-v/100);
  const pts = done.map((s,i)=>[x(i), y(s.report.scores.total), s]);
  const grid=[0,60,80,100].map(v=>`<line x1="${pl}" x2="${W-pr}" y1="${y(v)}" y2="${y(v)}" stroke="var(--line)"/><text x="${pl-4}" y="${y(v)+3}" text-anchor="end">${v}</text>`).join('');
  const line = n>1 ? `<polyline points="${pts.map(p=>p[0].toFixed(1)+','+p[1].toFixed(1)).join(' ')}" fill="none" stroke="var(--accent)" stroke-width="2"/>` : '';
  const area = n>1 ? `<polygon points="${pts[0][0]},${y(0)} ${pts.map(p=>p[0].toFixed(1)+','+p[1].toFixed(1)).join(' ')} ${pts[n-1][0]},${y(0)}" fill="var(--accent-soft)"/>` : '';
  const dots = pts.map((p,i)=>`<circle cx="${p[0]}" cy="${p[1]}" r="${i===n-1?4:2.5}" fill="var(--accent)"><title>${new Date(p[2].createdAt).toLocaleDateString('ru-RU')} · ${esc(p[2].manager||'')} · ${p[2].report.scores.total}</title></circle>`).join('');
  const first=done[0], last=done[n-1];
  const lbl = `<text x="${pts[0][0]}" y="${H-6}" text-anchor="${n===1?'middle':'start'}">${new Date(first.createdAt).toLocaleDateString('ru-RU')}</text>`+(n>1?`<text x="${pts[n-1][0]}" y="${H-6}" text-anchor="end">${new Date(last.createdAt).toLocaleDateString('ru-RU')}</text>`:'');
  const lastLbl = `<text x="${pts[n-1][0]}" y="${pts[n-1][1]-8}" text-anchor="${n===1?'middle':'end'}" style="fill:var(--ink);font-weight:600">${last.report.scores.total}</text>`;
  const delta = n>1 ? last.report.scores.total - first.report.scores.total : null;
  return `<svg viewBox="0 0 ${W} ${H}" width="100%" role="img" aria-label="Итоговый балл по выступлениям">${grid}${area}${line}${dots}${lastLbl}${lbl}</svg><p class="note">${n} ${plural(n,'разбор','разбора','разборов')}${delta!=null?` · изменение ${delta>0?'+':''}${delta} с первого`:''}</p>`;
}
