def detected_person(det, title, summary=""):
    if det["type"] == "workforce":
        return ""
    if det["type"] == "proceeding":
        return det.get("subject", "")
    if det["type"] == "award" and national_rector_award(title):
        return rector_award_actor(title) or extract_person(title)
    return extract_person(title) or extract_person(first_sentence(summary))


def national_rector_award(title):
    t = normalize(title)
    return bool(RECTOR_PRIZE.search(t) and RECTOR_PRIZE_NAME.search(t)
                and RECTOR_INSTITUTION.search(t))


def detect_all(title, summary, organizations):
    # Подтверждённое процессуальное событие о должностном лице сохраняем.
    proceeding = detect_proceedings(title, summary)
    if proceeding:
        return proceeding
    if bankruptcy_administrator_appointment(title, summary):
        return None
    if national_rector_award(title):
        return {"type": "award", "level": "head", "org_class": "podved",
                "orgs": find_org_names(title, organizations)}
    return (detect(title, summary, organizations)
            or detect_staffing(title, summary, organizations, find_org_names)
            or detect_extra(title, summary, organizations))




# HISTORICAL_APPOINTMENT_GUARD_20261124
# The event is a former job, not a new appointment: e.g., a detained person
# "возглавил компанию ... в конце 2020 года" in a new crime story from 2026.
HISTORICAL_JOB_ACTION = re.compile(
    r"\b(?:возглавил[аи]?|назначен[аоы]?|назначил[аи]?|"
    r"стал[аи]?\s+(?:(?:новым|новой)\s+)?(?:главой|директором|руководителем|председателем|гендиректором))\b",
    re.I,
)
HISTORICAL_ROLE_YEAR = re.compile(
    r"\b(?:в\s+(?:(?:самом\s+)?(?:конце|начале|середине)\s+)?|"
    r"с\s+(?:(?:самого\s+)?(?:конца|начала|середины)\s+)?)"
    r"(20\d{2})\b",
    re.I,
)
HISTORICAL_CAREER_CONTEXT = re.compile(
    r"\b(?:практически\s+с\s+самого|с\s+момента\s+(?:создан|основан|возникнов)|"
    r"ранее\s+(?:он|она)\s+возглавлял|много\s+лет\s+назад)\b",
    re.I,
)
CRIME_FOCUSED_HEADLINE = re.compile(
    r"^\s*(?:задержанн\w*|арестованн\w*|осужд[её]нн\w*|"
    r"обвиняем\w*|приговор[её]нн\w*|"
    r"(?:в\s+\S+\s+)?(?:задержал\w*|задержали|арестовал\w*|осудил\w*|"
    r"суд\s+(?:вынес|приговорил)))(?=\W)",
    re.I,
)
RECENT_REAL_APPOINTMENT = re.compile(
    r"\b(?:сегодня|вчера|накануне|на\s+днях|вновь|снова|повторно)\b"
    r".{0,85}?\b(?:возглавил[аи]?|назначен[аоы]?|назначил[аи]?|стал[аи]?)\b",
    re.I,
)


def historical_appointment_backstory(title, summary):
    """Old career fact reused in a recent publication; do not invent appointment.

    Only match an old year connected to an actual appointment verb, or an
    explicitly retrospective crime-focused headline. A true recent appointment
    of a replacement person in the same news is not suppressed.
    """
    title = normalize(title or '').strip()
    summary = normalize(summary or '').strip()
    crime_focus = bool(CRIME_FOCUSED_HEADLINE.search(title))
    # For a general news title we don't infer an appointment from background
    # summary paragraphs. The exact headline itself is the strongest evidence.
    context = title + (' ' + first_sentence(summary, limit=260) if crime_focus else '')
    # A word such as "сегодня" in "сегодня задержан" does NOT make the
    # historical appointment recent. For crime-led headlines, require an
    # explicit renewed appointment, not merely a recent detention.
    if RECENT_REAL_APPOINTMENT.search(title) and (not crime_focus or re.search(
        r"\b(?:вновь|снова|повторно)\b.{0,85}?\b(?:возглавил[аи]?|назначен[аоы]?)\b",
        title, re.I)):
        return False
    for verb in HISTORICAL_JOB_ACTION.finditer(context):
        # Retrospective date may also precede the verb: "В конце 2020 года
        # Шмидт возглавил...". Do not suppress "а теперь возглавил".
        earlier = context[max(0, verb.start() - 100):verb.start()]
        for dated in HISTORICAL_ROLE_YEAR.finditer(earlier):
            after_date = earlier[dated.end():]
            if (int(dated.group(1)) <= g.msk_today().year - 2
                    and not re.search(r"\b(?:а\s+теперь|теперь|ныне|сейчас|сегодня|накануне|вновь|снова)\b",
                                      after_date, re.I)):
                return True
        tail = context[verb.end():verb.end() + 215]
        for dated in HISTORICAL_ROLE_YEAR.finditer(tail):
            # "appointed ...; previously worked since 2020" is NOT an old
            # appointment. The date must belong to the same job clause.
            before_date = tail[:dated.start()]
            if re.search(r"(?:[.!?]\s|\b(?:до\s+этого|ранее|раньше|прежде|до\s+назначения|вместо)\b)",
                         before_date, re.I):
                continue
            # An old year is a career date; a current-year date could be a
            # newly published appointment and must not be discarded.
            if int(dated.group(1)) <= g.msk_today().year - 2:
                return True
        if crime_focus and HISTORICAL_CAREER_CONTEXT.search(tail):
            return True
    return False

# A Google News feed is a discovery channel, NOT evidence that an event
# belongs to the region named in its query.  Avoid "Водоканал" from a
# remote city inheriting the Saint Petersburg organization-dictionary entry.
# The decision is made on the event headline and its first lead, not on an
# entire scraped article containing incidental place names.
AMBIGUOUS_GEO_ORGANIZATIONS = frozenset({
    "водоканал", "метрострой", "теплосеть", "горводоканал", "университет",
    "политех", "администрация", "мэрия",
})
# Adjectival forms of large non-SZFO cities that the legacy NEWS_FOREIGN
# list (designed mainly for inflected city nouns) does not cover.
FOREIGN_CITY_ADJECTIVES = re.compile(
    r"\b(?:тульск|казанск|уфимск|нижегородск|самарск|ростовск|"
    r"свердловск|краснодарск|екатеринбургск|ульяновск|орловск|"
    r"белгородск|смоленск|ярославск|воронежск|челябинск)\w*", re.I)


def _street_name_mention(text, match):
    """The Belorusskaya street is not a story happening in Belarus."""
    before = (text or "")[max(0, match.start() - 45):match.start()]
    after = (text or "")[match.end():match.end() + 32]
    street = r"(?:улиц\w*|ул\.|проспект\w*|пр-т|переулк\w*|площад\w*|шосс\w*|бульвар\w*|набережн\w*)"
    return bool(re.search(r"\b" + street + r"\s+(?:имени\s+)?$", before, re.I)
                or re.match(r"^[а-яё\-]*\s+" + street + r"\b", after, re.I))


def local_context_foreign_matches(text):
    return [m for m in NEWS_FOREIGN.finditer(text or "")
            if not _street_name_mention(text, m)]


def foreign_place_matches(text):
    return local_context_foreign_matches(text) + list(FOREIGN_CITY_ADJECTIVES.finditer(text or ""))


def has_foreign_place(text):
    return bool(foreign_place_matches(text) or g._has_foreign_region(text or ""))


def foreign_place_qualifies_organization(title):
    """A city belongs to the *named enterprise*, not to an author's bio.

    Examples: 'Оренбург Водоканал', 'Тульский водоканал',
    'Водоканал Оренбурга'. Also works when Petersburg is mentioned as the
    place where a reporter heard news about an enterprise elsewhere.
    """
    kind = r"(?:водоканал\w*|горводоканал\w*|метростро\w*|теплосет\w*|" \
           r"университет\w*|завод\w*|комбинат\w*|предприяти\w*|компани\w*)"
    for foreign in foreign_place_matches(title):
        tail = title[foreign.end():foreign.end()+55]
        if re.match(r"^[а-яё]{0,14}[\s\-«»]{1,8}" + kind + r"\b", tail, re.I):
            return True
        prior = title[max(0, foreign.start()-40):foreign.start()]
        if re.search(r"\b" + kind + r"[\s«»]{1,5}$", prior, re.I):
            return True
    return False


def explicit_szfo_place(text):
    """An explicit SZFO place mentioned in *text*, independent of foreign hits.

    Unlike news_region(), this can detect mixed-region headlines ("an expert
    from Orenburg appointed in Petersburg"). It is not sufficient by itself
    to accept a story; the normal relevance filter still applies.
    """
    if not text:
        return False
    for _region, _slug, patterns in g.SZFO_COMPILED:
        if any(p.search(text) for p in patterns):
            return True
    return any(any(p.search(text) for p in pats)
               for _region, pats in _NEWS_REGION_COMPILED)


def outside_szfo_event_focus(title, summary="", source=None, orgs=(), event_type=""):
    """Reject clear non-SZFO subjects before organization-based relevance.

    Google News queries and short generic enterprise names are not
    geographical evidence. The actual event must be located in the SZFO.
    Biographical origins remain permissible when the headline explicitly
    identifies an SZFO event location.
    """
    title = title or ""
    lead = first_sentence(summary or "", limit=260)
    title_foreign = has_foreign_place(title)
    title_local = explicit_szfo_place(title)
    # A qualified foreign company name is an event subject even if the
    # headline says that it was discussed *in* Saint Petersburg.
    if title_foreign and foreign_place_qualifies_organization(title):
        return True
    if title_foreign and not title_local:
        # An award of a uniquely named local institution may be presented
        # outside the SZFO (e.g. Севмаш awarded at a Moscow ceremony). The
        # recipient, not the ceremony venue, defines its regional relevance.
        if event_type in ("award", "title") and any(
                name.casefold() not in AMBIGUOUS_GEO_ORGANIZATIONS
                and org_pattern(name).search(title)
                for _region, name in orgs):
            return False
        return True
    # Syndication may omit the location from the title but provide it in the
    # lead. Only generic organization names need this fallback; 'Севмаш' etc.
    # are distinctive local names and should not be discarded on biography.
    if not explicit_szfo_place(title + " " + lead):
        generic = any(name.casefold().strip(' «»"') in AMBIGUOUS_GEO_ORGANIZATIONS
                      for _region, name in orgs)
        if generic and has_foreign_place(lead):
            return True
        # A Google News source is labelled with the SEARCH region, not with
        # the region of any given article. Generic names alone cannot anchor.
        if source and source.get("region_from_text") and generic:
            return True
    return False


# Regional infrastructure monitoring: a routine street-level connection is
# not the kind of large commissioning represented by the "launch" category.
# ``газопровод`` in LAUNCH_SCALE previously sufficed on its own, regardless
# of whether the work served twenty homes or a whole region.
LOCAL_UTILITY_SUBJECT = re.compile(
    r"\b(?:газопровод\w*|водопровод\w*|теплопровод\w*|теплосет\w*|"
    r"газоснабжен\w*|водоснабжен\w*|водоотведен\w*|догазификац\w*|"
    r"канализационн\w*\s+сет\w*|электросет\w*|"
    r"сет\w*\s+(?:газ\w*|вод\w*|электроснабжен\w*|теплоснабжен\w*))\b",
    re.I,
)
MAJOR_UTILITY_CONTEXT = re.compile(
    r"\b(?:магистральн\w*|межрегиональн\w*|международн\w*|"
    r"газоперерабатывающ\w*|газохимическ\w*|нефтехимическ\w*|"
    r"газосжижен\w*|\bСПГ\b|"
    r"(?:крупнейш\w*|стратегическ\w*)\s+"
    r"(?:проект\w*|объект\w*|магистрал\w*|комплекс\w*)|"
    r"промышленн\w*\s+(?:предприяти\w*|площадк\w*|комплекс\w*)|"
    r"индустриальн\w*\s+парк\w*|газопровод\w*\s+для\s+завод\w*|"
    r"поставк\w*\s+газа\s+на\s+завод\w*)\b",
    re.I,
)
UTILITY_LENGTH_KM = re.compile(
    r"\b(?:протяж[её]нност\w*|длин\w*|проложил\w*|построил\w*)"
    r"[^.!?]{0,55}?\b(\d+(?:[.,]\d+)?)\s*(?:км|километр\w*)\b",
    re.I,
)
UTILITY_HOUSEHOLDS = re.compile(
    r"\b(\d[\d \u00a0]{0,9})\s+(?:домовладен\w*|домохозяйств\w*|жил\w*\s+дом\w*)\b",
    re.I,
)
UTILITY_INVESTMENT = re.compile(
    r"\b(?:\d+(?:[.,]\d+)?\s*млрд|\d+(?:[.,]\d+)?\s*миллиард\w*)\s*(?:рубл\w*|₽)",
    re.I,
)


def minor_local_utility_launch(title, summary=""):
    """Conservatively reject small/unsized distribution-network launches.

    A large main pipeline or a demonstrably strategic, regional/industrial
    project can pass. Unknown scale is not evidence of major significance.
    This applies to launch only, never appointments or court decisions.
    """
    title = normalize(title or "")
    if not LOCAL_UTILITY_SUBJECT.search(title):
        return False
    anchor = title + " " + first_sentence(normalize(summary or ""), limit=550)
    if MAJOR_UTILITY_CONTEXT.search(anchor) or UTILITY_INVESTMENT.search(anchor):
        return False
    if any(float(m.group(1).replace(",", ".")) >= 50 for m in UTILITY_LENGTH_KM.finditer(anchor)):
        return False
    for m in UTILITY_HOUSEHOLDS.finditer(anchor):
        if int(re.sub(r"\D", "", m.group(1))) >= 1000:
            return False
    return True


# Ожидания гостиничных открытий и незавершённые стройки — не ввод объекта.
# Требуется контекст И незавершённости, и гостиничного объекта, а не один
# запрет слова «гостиница» (иначе потеряем реальные открытия крупных отелей).
HOSPITALITY_OBJECT = re.compile(r"\b(?:гостиниц\w*|отел[ьяюе]\w*|гостев\w*\s+дом\w*)", re.I)
