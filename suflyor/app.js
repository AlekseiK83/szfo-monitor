function normText(s){ return String(s||'').toLowerCase().replace(/ё/g,'е').replace(/[^a-zа-я0-9]+/g,' ').trim(); }
function tokens(s){ const n = normText(s); return n ? n.split(' ') : []; }
function fmtTime(sec){ if(sec==null||!isFinite(sec)) return '—'; sec=Math.round(sec); const h=Math.floor(sec/3600), m=Math.floor(sec%3600/60), s=sec%60; return (h?h+':'+String(m).padStart(2,'0'):m)+':'+String(s).padStart(2,'0'); }
function parseClock(str){
  const m = String(str||'').trim().match(/^(?:(\d{1,2}):)?(\d{1,3}):(\d{2})(?:[.,]\d+)?$/);
  if(!m) return null;
  return (+(m[1]||0))*3600 + (+m[2])*60 + (+m[3]);
}

/* Разбирает сырой ввод: заголовок длительности, таймкоды [мм:сс], форматы SRT/VTT. */
function parseTranscript(raw){
  const out = {text:'', lines:[], duration:null, timed:false};
  let src = String(raw||'').replace(/\r/g,'');
  const durM = src.match(/^\s*(?:длительность|duration)\s*[:：]\s*([\d:.,]+)\s*$/im);
  if(durM) out.duration = parseClock(durM[1]);
  const isCue = /-->/.test(src);
  let maxT = 0;
  const lines = [];
  if(isCue){
    let curT = null;
    for(const ln of src.split('\n')){
      const l = ln.trim();
      if(!l || /^webvtt/i.test(l) || /^\d+$/.test(l) || /^(note|style)\b/i.test(l)) continue;
      const cue = l.match(/([\d:.,]+)\s*-->\s*([\d:.,]+)/);
      if(cue){ curT = parseClock(cue[1]); const e = parseClock(cue[2]); if(e!=null) maxT=Math.max(maxT,e); continue; }
      const txt = l.replace(/<[^>]+>/g,'').trim();
      if(txt) lines.push({t:curT, text:txt});
    }
  } else {
    for(const ln of src.split('\n')){
      const l = ln.trim();
      if(!l || /^\s*(?:длительность|duration)\s*[:：]/i.test(l)) continue;
      const tm = l.match(/^\[?((?:\d{1,2}:)?\d{1,3}:\d{2})\]?\s+(.*)$/);
      if(tm){ const t=parseClock(tm[1]); if(t!=null) maxT=Math.max(maxT,t); lines.push({t, text:tm[2].trim()}); }
      else lines.push({t:null, text:l});
    }
  }
  out.lines = lines.filter(x=>x.text);
  out.timed = out.lines.some(x=>x.t!=null);
  out.text = out.lines.map(x=>x.text).join('\n');
  if(out.duration==null && maxT>0){
    // последний таймкод — начало последней фразы; добавим оценку её длительности (2,5 слова/сек)
    const last = out.lines[out.lines.length-1];
    out.duration = maxT + (last && last.t===maxT ? Math.ceil(tokens(last.text).length/2.5) : 0);
  }
  return out;
}

