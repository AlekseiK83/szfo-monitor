/* Нарезка аудио на куски ≤ 28 с по самым тихим местам; тишину пропускаем. */
function splitChunks(samples, sr, target=28, search=4){
  const frame = Math.round(sr*0.02), nF = Math.floor(samples.length/frame);
  const en = new Float32Array(nF);
  for(let f=0; f<nF; f++){ let s=0; const o=f*frame; for(let i=0;i<frame;i++){ const v=samples[o+i]; s+=v*v; } en[f]=Math.sqrt(s/frame); }
  const chunks=[]; let start=0;
  while(start < samples.length){
    let end = Math.min(samples.length, start + target*sr);
    if(end < samples.length){
      const fA = Math.floor((end - search*sr)/frame), fB = Math.floor(end/frame);
      let best=fB, bv=Infinity; for(let f=Math.max(fA, Math.floor(start/frame)+1); f<fB && f<nF; f++){ if(en[f]<bv){ bv=en[f]; best=f; } }
      end = Math.max(start+sr, best*frame);
    }
    let s=0, c=0; for(let f=Math.floor(start/frame); f<Math.floor(end/frame) && f<nF; f++){ s+=en[f]; c++; }
    const rms = c ? s/c : 0;
    if(end-start > sr*0.5) chunks.push({start, end, silent: rms < 0.004});
    start = end;
  }
  return chunks;
}
/* Известные «галлюцинации» Whisper на русском при тишине и шуме. */
const HALLU = [/субтитр/i, /продолжение следует/i, /спасибо за просмотр/i, /dimatorzok/i, /редактор субтитров/i, /подписывайтесь на канал/i, /корректор/i, /^[\s\p{P}\p{S}]*$/u];
function cleanWhisper(t){
  t = String(t||'').replace(/\s+/g,' ').trim();
  if(!t || HALLU.some(r=>r.test(t))) return '';
  // повторяющиеся фразы — частая петля декодера
  t = t.replace(/(^|\s)([^.!?]{4,60}?[.!?]?)(?:\s+\2){2,}/giu, '$1$2');
  return t;
}
