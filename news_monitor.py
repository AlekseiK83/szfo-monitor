def post_title(text, limit=160):
    """Заголовок для поста без заголовка (Telegram): первое предложение; если оно длиннее лимита —
    обрезка по границе слова с многоточием, а не посреди слова."""
    lines = [ln.strip() for ln in text.split("\n") if ln.strip()]
    if len(lines) > 1 and (re.match(r"(?:информаци[яи]|сообщени[ея]|внимание|важно|анонс|срочно|новост[ьи]|пресс-релиз|официально|заявление)\b", lines[0], re.I)
                           or (len(lines[0].split()) <= 4 and not re.search(r"[.!?]$", lines[0]) and len(lines[1]) > 30)):
        lines = lines[1:]                                    # служебная первая строка («Информация Жилищного комитета») — не заголовок
    text = re.sub(r"\s+", " ", " ".join(lines)).strip()
    # граница предложения: не инициал («А.В. Иванов»), не сокращение («им.», «ул.», «г.», «т.е.»)
    m = re.search(r"(?<![А-ЯЁ])(?<!\bим)(?<!\bул)(?<!\bг)(?<!\bт)(?<!\bе)(?<!\bпр)(?<!\bд)(?<!\bстр)[.!?…](?:[»\"])?\s+(?=[А-ЯЁA-Z0-9«\"])", text)
    if m and m.end() <= limit + 20:
        return text[:m.start() + 1].rstrip(" ")
    if len(text) <= limit:
        return text
    cut = text.rfind(" ", 40, limit)
    return text[:cut if cut > 0 else limit].rstrip(" ,;:—-") + "…"


def telegram_post_title(text):
    """Первая осмысленная строка/заголовок Telegram, включая перенос посреди фразы.

    Не склеиваем обычную новостную шапку с началом следующего абзаца.
    """
    lines = text.split("\n")
    first = lines[0].strip() if lines else ""
    if len(lines) > 1 and lines[1].strip():
        continuation = lines[1].strip()
        incomplete = bool(re.search(
            r"(?:\b(?:на\s+(?:стадии|этапе)|в\s+ходе)|"
            r"\b(?:в|во|на|для|из|от|по|при|о|об|с|со|к|и|что)|[,;:—-])$",
            first, re.I))
        # Начало второй строки со строчной буквы часто означает обычный
        # перенос заголовка, а не новый абзац.
        continued_lowercase = (len(first) < 135 and continuation[0].islower()
                               and not re.search(r"[.!?…]$", first)
                               and not APPOINT_VERB.search(first))
        # Региональное имя с заглавной буквы тоже бывает продолжением:
        # «... сессии Госсовета\nКоми». Не склеивать с самостоятельным
        # абзацем или URL на первоисточник.
        continued_region = bool(
            len(first) < 240
            and not re.search(r"[.!?…]$", first)
            and re.search(r"\b(?:госсовет\w*|республик\w*|правительств\w*|област\w*|собрани\w*)$", first, re.I)
            and re.fullmatch(
                r"(?:Коми|Карелии|Карелия|Петербурга|Санкт-Петербурга|"
                r"Мурманской|Псковской|Архангельской|Вологодской|"
                r"Новгородской|Ленинградской|Калининградской)"
                r"(?:\s+(?:области|республики))?",
                continuation, re.I))
        if incomplete or continued_lowercase or continued_region:
            first = first + " " + continuation
    if len(first) < 20 and "\n" in text:
        return post_title(text)
    # 160 символов — ограничение короткой аннотации, а не заголовка
    # исходного Telegram-поста. На странице сохраняем длинные заголовки.
    return post_title(first, limit=260)


